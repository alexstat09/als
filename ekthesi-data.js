  /* ⭐⭐ ΤΟ ΣΤΟΙΧΕΙΟ ΕΙΝΑΙ `{w, alt}`, ΚΑΙ ΤΟ `alt` ΤΟ ΓΕΝΝΗΣΕ ΤΟ TEST.
     Ο χειρόγραφος πίνακας του `tests/ekthesi-engine.test.js` έσκασε στο
     «φιλεύσπλαγχνος» vs «φιλεύσπλαχνος» — και είχε δίκιο να σκάσει, αλλά
     όχι όπως νόμιζα. ΔΕΝ είναι ορθογραφικό λάθος του Αλεξ: το «σπλάχνο»
     και το «σπλάγχνο» είναι ΔΥΟ ΑΠΟΔΕΚΤΕΣ ΟΡΘΟΓΡΑΦΙΕΣ της ίδιας λέξης, η
     μία απλοποιημένη και η άλλη ετυμολογική. Το ίδιο θα ξανασυμβεί με
     αβγό/αυγό, τρένο/τραίνο, αφτί/αυτί.

     ⚠️ Η ΛΥΣΗ ΔΕΝ ΕΙΝΑΙ ΝΑ ΧΑΛΑΡΩΣΕΙ Η ΜΗΧΑΝΗ. Ένας κανόνας «γχ ≡ χ» μέσα
     στο `greek-ear.js` θα άγγιζε ΚΑΙ την Ιστορία ΚΑΙ τα Αρχαία (σταθερή
     αρχή 25) για να λύσει ένα πρόβλημα λεξικού. Η γνώση ότι δύο γραφές
     είναι η ίδια λέξη ανήκει ΣΤΟ ΥΛΙΚΟ, όπου την έγραψε άνθρωπος που την
     ξέρει — όχι σε έναν φωνητικό κανόνα που θα την μαντεύει παντού.

     Ο συγγραφέας γράφει σκέτη συμβολοσειρά (το 99%) ή ΠΙΝΑΚΑ με την
     κανονική γραφή ΠΡΩΤΗ:
         'αγνός'                              → μία γραφή
         ['φιλεύσπλαχνος', 'φιλεύσπλαγχνος']  → η πρώτη είναι αυτή που δείχνουμε
     Ο κατασκευαστής κανονικοποιεί, ώστε η μηχανή να βλέπει ΠΑΝΤΑ `{w, alt}`
     και να μη χρειάζεται να ρωτάει τι τύπος ήρθε. */
  function item(x) {
    if (Object.prototype.toString.call(x) === '[object Array]') {
      return { w: String(x[0]), alt: x.slice(1).map(String) };
    }
    return { w: String(x), alt: [] };
  }

  /* ⭐ Ο ΚΑΤΑΣΚΕΥΑΣΤΗΣ ΚΡΑΤΑΕΙ ΤΟΝ ΠΙΝΑΚΑ ΠΙΝΑΚΑ. Το υλικό παρακάτω πρέπει
     να διαβάζεται σαν τη σελίδα του βιβλίου — αν χρειαζόταν να γράψω
     `{groups:[{id:'syn',label:…}]}` δεκαέξι φορές, θα έμπαινε λάθος και δεν
     θα φαινόταν. ΜΙΑ ΑΔΕΙΑ ΟΜΑΔΑ ΔΕΝ ΜΠΑΙΝΕΙ ΚΑΘΟΛΟΥ: τρία λήμματα της
     σελίδας 547 δεν έχουν αντώνυμα στο βιβλίο, και ένα κενό κουτί
     «αντώνυμα» θα του ζητούσε να θυμηθεί κάτι που δεν υπάρχει. */
  function group(id, list) {
    return { id: id, label: GROUPS[id].label, short: GROUPS[id].short, items: list.map(item) };
  }
  function card(id, q, syn, ant, note) {
    var g = [];
    if (syn && syn.length) g.push(group('syn', syn));
    if (ant && ant.length) g.push(group('ant', ant));
    return { id: id, q: q, groups: g, note: note || '' };
  }

