/* ══════════════════════════════════════════════════════════════════════
   study-stamp.js — Η ΣΦΡΑΓΙΔΑ ΠΟΥ ΚΑΝΕΙ ΤΗΝ ΠΡΟΟΔΟ ΝΑ ΕΠΙΒΙΩΝΕΙ ΤΟΥ SYNC

   ⭐⭐ ΤΟ ΛΑΘΟΣ ΠΟΥ ΤΟ ΓΕΝΝΗΣΕ (9 Αυγ 2026, als-v468).
   Ο Αλεξ έκανε ΕΠΑΝΑΛΗΨΗ στο 1ο κεφάλαιο της Ιστορίας, το είπε ολόκληρο, η
   σελίδα του είπε «τέλεια, ξανά σε 10 μέρες» — και μόλις γύρισε πίσω το
   σπίτι έλεγε «έληξε χθες». Η επανάληψη δεν χάθηκε στην οθόνη: χάθηκε στο
   `sync.js`.

   Το `mergeObject` κατεβαίνει αναδρομικά μέσα σε φωλιασμένα αντικείμενα και
   στο ΤΕΛΟΣ, για κάθε ΒΑΘΜΩΤΟ κλειδί που διαφέρει, κάνει `out[key] = rv` —
   «remote wins → converges». Άρα το `units.a1a.due` που μόλις γράφτηκε
   ΤΟΠΙΚΑ (τώρα + 10 μέρες) αντικαθίστατο ΠΑΝΤΑ από την παλιά τιμή του
   cloud, το `applyLocal` την ξανάγραφε στο localStorage και το ίδιο sync
   την έσπρωχνε πίσω επάνω. Ντετερμινιστικό, όχι κούρσα: κάθε ενημέρωση
   εγγραφής που ΥΠΗΡΧΕ ήδη στο cloud γυρνούσε πίσω μέσα σε ~400ms. Γι' αυτό
   η ΠΡΩΤΗ ανάκληση μιας ενότητας «δούλευε» (καινούριο κλειδί → κρατιόταν)
   και η δεύτερη όχι — ακριβώς αυτό που περιέγραψε.

   Χειρότερο από την επαναφορά: το merge γίνεται ΑΝΑ ΠΕΔΙΟ, οπότε μια
   εγγραφή μπορούσε να καταλήξει με `reviews` από τη μια γενιά και `best`
   από την άλλη. Τα `due`/`reviews`/`best`/`runs` ΔΕΝ είναι ανεξάρτητα
   νούμερα· είναι μία μέτρηση.

   ⭐ Η ΘΕΡΑΠΕΙΑ ΕΙΝΑΙ Ο ΜΗΧΑΝΙΣΜΟΣ ΠΟΥ ΥΠΗΡΧΕ ΗΔΗ. Το `sync.js` δίνει
   ρητό opt-in σε last-write-wins ΑΝΑ ΑΝΤΙΚΕΙΜΕΝΟ:

       if (('_ts' in lv) || ('_ts' in rv)) return (lv._ts >= rv._ts) ? lv : rv;

   Δεν το χρησιμοποιούσε καμία σελίδα μελέτης με χάρτη εγγραφών. Τα
   Λατινικά επιβίωναν κατά τύχη: τα κελιά τους είναι ΠΙΝΑΚΑΣ με `id` + `ts`,
   και οι πίνακες συγχωνεύονται με «κερδίζει ο νεότερος». Ίδιος νόμος, άλλο
   σχήμα — και μόνο το ένα από τα δύο τον είχε.

   ⭐⭐ Η ΣΦΡΑΓΙΔΑ ΜΠΑΙΝΕΙ ΣΕ ΕΝΑ ΣΗΜΕΙΟ, ΟΧΙ ΣΤΑ ΔΩΔΕΚΑ ΠΟΥ ΓΡΑΦΟΥΝ.
   Ένα `_ts = Date.now()` σκορπισμένο σε κάθε ανάθεση είναι μια σφραγίδα
   που κάποιος ΘΑ ξεχάσει την επόμενη φορά — και η αποτυχία της είναι
   αόρατη: σωστή οθόνη, σωστό localStorage, και η τιμή γυρίζει πίσω μετά
   από 400ms. Άρα σφραγίζει το `save()`: συγκρίνει κάθε εγγραφή με το
   ΤΕΛΕΥΤΑΙΟ ΓΝΩΣΤΟ αποτύπωμά της και σφραγίζει ΜΟΝΟ όσες άλλαξαν
   πραγματικά. Καμία σελίδα δεν μπορεί να ξεχάσει κάτι που δεν γράφει.

   ΤΡΕΙΣ ΚΑΝΟΝΕΣ ΠΟΥ ΕΙΝΑΙ ΟΛΟΙ ΑΜΥΝΑ:

   1. ⭐ ΑΔΕΙΑ ΕΓΓΡΑΦΗ ΔΕΝ ΠΑΙΡΝΕΙ ΠΟΤΕ ΣΦΡΑΓΙΔΑ. Το `u(id)` φτιάχνει
      `{learnedAt:0, reviews:0, …}` απλώς και μόνο επειδή κάποιος ΤΗ ΔΙΑΒΑΣΕ
      σε ένα render. Αν αυτό το μηδενικό κέλυφος έπαιρνε φρέσκια σφραγίδα,
      θα κέρδιζε την ΑΛΗΘΙΝΗ εγγραφή του cloud και θα έσβηνε την πρόοδο —
      η σταθερή αρχή «ένα default δεν είναι δεδομένο» με write στο τέλος,
      δηλαδή ακριβώς το bug του `nut:streak` σε άλλη σελίδα.
   2. ⭐ Η ΣΠΟΡΑ ΔΕΝ ΕΙΝΑΙ ΣΦΡΑΓΙΣΜΑ. Σε κάθε `load()` παίρνουμε αποτύπωμα
      ΧΩΡΙΣ να σφραγίσουμε τίποτα. Αλλιώς μια συγχώνευση που μόλις ΗΡΘΕ από
      το cloud θα σφραγιζόταν σαν δική μας φρέσκια αλλαγή, και μια παλιά
      συσκευή θα νικούσε μια νεότερη με δανεικό χρόνο.
   3. ⭐ ΟΙ ΠΑΛΙΕΣ ΕΓΓΡΑΦΕΣ ΠΑΙΡΝΟΥΝ ΤΟΝ ΠΡΑΓΜΑΤΙΚΟ ΤΟΥΣ ΧΡΟΝΟ, ΟΧΙ ΤΟ ΤΩΡΑ.
      Ό,τι υπάρχει ήδη στο κινητό του γράφτηκε πριν από αυτό το αρχείο και
      δεν έχει `_ts`. Η σπορά του δίνει την ώρα της τελευταίας ΑΛΗΘΙΝΗΣ
      δραστηριότητας (`last`/`learnedAt`), που την ξέρουμε. Ένα `Date.now()`
      εκεί θα σήμαινε «όποια συσκευή άνοιξε τελευταία τη σελίδα κερδίζει»,
      που είναι το ίδιο bug ανάποδα.

   Χρήση:
       var STAMP = window.StudyStamp(
         function(){ return [state.units, state.els]; },   // οι χάρτες
         function(i, k, rec){ return … }                   // παλιός χρόνος
       );
       function reload(){ state = load(); STAMP.seed(); }
       function save(){ STAMP.stamp(); localStorage.setItem(KEY, …); }
   ══════════════════════════════════════════════════════════════════════ */
(function () {
  'use strict';
  var has = Object.prototype.hasOwnProperty;

  /* Το αποτύπωμα αγνοεί το ίδιο το `_ts` — αλλιώς κάθε σφράγισμα θα
     φαινόταν αλλαγή και θα γεννούσε το επόμενο, για πάντα. Και είναι
     ΤΑΞΙΝΟΜΗΜΕΝΟ: το JSON.stringify σέβεται τη σειρά εισαγωγής των
     κλειδιών, οπότε δύο ταυτόσημες εγγραφές γραμμένες με άλλη σειρά θα
     έδιναν ψεύτικη διαφορά και ψεύτικη σφραγίδα. */
  function sig(rec) {
    var k, ks = [], i, out = '';
    for (k in rec) if (has.call(rec, k) && k !== '_ts') ks.push(k);
    ks.sort();
    for (i = 0; i < ks.length; i++) out += ks[i] + '\u0001' + JSON.stringify(rec[ks[i]]) + '\u0002';
    return out;
  }

  /* Κανόνας 1. Μηδενικά παντού = κέλυφος που έφτιαξε ένα render, όχι μέτρηση. */
  function empty(rec) {
    var k;
    for (k in rec) if (has.call(rec, k) && k !== '_ts' && rec[k]) return false;
    return true;
  }

  window.StudyStamp = function (readMaps, legacyTs) {
    var snap = null;

    function walk(seeding, now) {
      var maps = readMaps() || [], first = !snap, next = [], i, m, prev, cur, k, rec, s, t;
      for (i = 0; i < maps.length; i++) {
        m = maps[i] || {}; cur = {}; prev = (snap && snap[i]) || null;
        for (k in m) {
          if (!has.call(m, k)) continue;
          rec = m[k];
          if (!rec || typeof rec !== 'object' || Array.isArray(rec)) continue;
          s = sig(rec);
          cur[k] = s;
          if (empty(rec)) continue;
          if (seeding) {
            /* Κανόνας 3 — και μόνο όταν λείπει· ποτέ πάνω από υπάρχουσα. */
            if (typeof rec._ts !== 'number' || !rec._ts) {
              t = legacyTs ? (+legacyTs(i, k, rec) || 0) : 0;
              if (t) rec._ts = t;
            }
          } else if (!first && (!prev || prev[k] !== s)) {
            /* `!first`: αν μια σελίδα ξεχάσει τη σπορά, το πρώτο save δεν
               σφραγίζει τίποτα αντί να σφραγίσει τα πάντα. Η αποτυχία
               γέρνει προς «δεν κέρδισα», ποτέ προς «έσβησα το cloud». */
            rec._ts = now;
          }
        }
        next.push(cur);
      }
      snap = next;
    }

    return {
      seed: function () { walk(true, 0); },
      stamp: function (now) { walk(false, now || Date.now()); }
    };
  };
})();
