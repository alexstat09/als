  /* Ελληνική κανονικοποίηση: πεζά, χωρίς τόνους, τελικό σίγμα → σίγμα.
     Ίδια λογική με το fold() της βιβλιοθήκης — «προσευχή» πρέπει να
     ταιριάζει με «προσευχη» ή η αναγνώριση φωνής δεν πιάνει ποτέ τίποτα. */
  function fold(s) {
    return String(s == null ? '' : s)
      .toLowerCase()
      .normalize('NFD').replace(/[̀-ͯ]/g, '')
      .replace(/ς/g, 'σ')
      .replace(/[^Ͱ-ϿA-Za-z0-9]+/g, ' ')
      .trim();
  }

  /* Ένα σημείο θεωρείται «ειπωμένο» αν ΚΑΠΟΙΑ από τις εναλλακτικές του
     φράσεις υπάρχει ολόκληρη μέσα σε ό,τι ακούστηκε.  Εναλλακτική = πίνακας
     λέξεων· πρέπει να υπάρχουν ΟΛΕΣ.  Έτσι το ['μικρη','εκταση'] δεν
     πυροδοτείται από ένα σκέτο «μικρή». */
  function said(point, heard) {
    var hay = ' ' + fold(heard) + ' ', i, j, alts = point.say || [], ok;
    for (i = 0; i < alts.length; i++) {
      ok = true;
      for (j = 0; j < alts[i].length; j++) {
        if (hay.indexOf(' ' + fold(alts[i][j])) < 0 && hay.indexOf(fold(alts[i][j])) < 0) { ok = false; break; }
      }
      if (ok && alts[i].length) return true;
    }
    return false;
  }

