  /* Ελληνική κανονικοποίηση: πεζά, χωρίς τόνους, τελικό σίγμα → σίγμα.
     Ίδια λογική με το fold() της βιβλιοθήκης — «προσευχή» πρέπει να
     ταιριάζει με «προσευχη» ή η αναγνώριση φωνής δεν πιάνει ποτέ τίποτα. */
  function fold(s) {
    return String(s == null ? '' : s)
      .toLowerCase()
      .normalize('NFD').replace(/[̀-ͯ]/g, '')
      .replace(/ς/g, 'σ')
      .replace(/[^Ͱ-ϿA-Za-z0-9]+/g, ' ')
      .trim();
  }

  /* ⭐⭐ ΕΝΑ ΣΗΜΕΙΟ ΔΕΝ ΕΙΝΑΙ ΜΙΑ ΛΕΞΗ-ΚΛΕΙΔΙ.
     Η πρώτη έκδοση άναβε ολόκληρο σημείο μόλις ακουγόταν ΜΙΑ λέξη του, και ο
     Αλεξ το έπιασε αμέσως: «λεω μια λεξη που θελει να ακουσει και μου λεει οτι
     το βρηκα το ποιντ ενω μπορει να χω ξεχασει δυο τρεις λεξεις».  Είχε δίκιο
     και ήταν χειρότερο από άχρηστο: ένα εργαλείο που ανταμείβει μία λέξη
     ΔΙΔΑΣΚΕΙ ότι μία λέξη αρκεί.
     Τώρα κάθε σημείο σπάει σε ΣΤΟΙΧΕΙΑ (`must`) — τα ξεχωριστά γεγονότα μέσα
     του — και βαθμολογείται σε πόσα από αυτά ειπώθηκαν.  Ένα σημείο είναι
     ΠΛΗΡΕΣ μόνο αν ειπώθηκαν όλα. */

