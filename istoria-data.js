  /* Όλο το αυτολεξεί κείμενο μιας ενότητας, ενωμένο — αυτό ελέγχει το test
     και πάνω σε αυτό επαληθεύονται τα anchors. */
  function bodyOf(u) {
    var out = [], i;
    for (i = 0; i < (u.text || []).length; i++) out.push(u.text[i].p);
    return out.join('\n');
  }

