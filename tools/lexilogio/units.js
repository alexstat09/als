const cards = [];
for (const p of data.pages) for (const c of p.cards) cards.push(c);
const byFam = new Map();
for (const c of cards) { if (!byFam.has(c.family)) byFam.set(c.family, []); byFam.get(c.family).push(c); }

const seenFam = new Set(), seenId = new Set(), errs = [];
const units = PLAN.map(([title, fams], i) => {
  const ids = [];
  for (const f of fams) {
    if (f.startsWith('M:')) {
      const c = (byFam.get('Μεμονωμένες') || []).find(x => x.front === f.slice(2));
      if (!c) { errs.push('δεν βρέθηκε μεμονωμένη ' + f); continue; }
      ids.push(c.id); continue;
    }
    if (!byFam.has(f)) { errs.push('άγνωστη οικογένεια ' + f); continue; }
    if (seenFam.has(f)) errs.push('οικογένεια δύο φορές ' + f);
    seenFam.add(f);
    for (const c of byFam.get(f)) ids.push(c.id);
  }
  for (const id of ids) { if (seenId.has(id)) errs.push('διπλό id ' + id); seenId.add(id); }
  const n = i + 1;
  if (ids.length < 20 || ids.length > 30) errs.push('ενότητα ' + n + ': ' + ids.length + ' λέξεις');
  return { id: 'u' + String(n).padStart(2, '0'), n, title, ids };
});
for (const c of cards) if (!seenId.has(c.id)) errs.push('λείπει ' + c.id + ' (' + c.family + ')');
if (errs.length) { console.error(errs.join('\n')); process.exit(1); }

const out = {
  schema: 1,
  source: 'data/lexilogio.json — ίδιες λέξεις, ίδια ids· εδώ μόνο η ομαδοποίηση. Χτίζεται από tools/lexilogio/units.js.',
  units,
};
const json = '{\n  "schema": 1,\n  "source": ' + JSON.stringify(out.source) + ',\n  "units": [\n' +
  units.map(u => '    {"id": ' + JSON.stringify(u.id) + ', "n": ' + u.n + ', "title": ' + JSON.stringify(u.title) +
    ',\n     "ids": ' + JSON.stringify(u.ids) + '}').join(',\n') + '\n  ]\n}\n';
