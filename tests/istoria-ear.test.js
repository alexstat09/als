/* ── 5 · ΤΟ ΑΥΤΙ ΔΕΝ ΣΥΓΧΩΝΕΥΕΙ ΔΥΟ ΔΙΑΦΟΡΕΤΙΚΑ ΣΤΟΙΧΕΙΑ ───────────── */
(function () {
  var seen = {}, clash = 0;
  I.UNITS.forEach(function (u) {
    u.skeleton.points.forEach(function (p) {
      p.must.forEach(function (e) {
        var k = u.id + '|' + JSON.stringify(e.say.map(function (a) { return a.map(I.pho); }));
        if (seen[k] && seen[k] !== e.k) { clash++; console.log('  ✗ ΣΥΓΚΡΟΥΣΗ: «' + e.k + '» ≡ «' + seen[k] + '»'); }
        seen[k] = e.k;
      });
    });
  });
  eq(clash, 0, '⭐ κανένα ζευγάρι στοιχείων δεν γίνεται ίδιο μετά το φωνητικό fold');
})();

/* ── 5β · ⭐⭐ ΚΑΝΕΝΑ ΣΤΟΙΧΕΙΟ ΔΕΝ ΑΝΑΒΕΙ ΑΠΟ ΑΛΛΟ ΣΗΜΕΙΟ ─────────────
   ΒΡΕΘΗΚΕ ΚΟΙΤΑΖΟΝΤΑΣ ΕΝΑ RENDER: το «απουσίαζαν τα ισχυρά κέντρα ανάπτυξης»
   άναβε επειδή είπε «ισχυρά κέντρα ελληνισμού» — ΑΛΛΟ σημείο της ίδιας
   ενότητας.  Πέντε τέτοια υπήρχαν, τα τέσσερα προϋπήρχαν του φωνητικού αυτιού
   και το ένα το γέννησε αυτό: χωρίς κενά, το «δεν διέθετε» περιέχει «ένδεια».
   ⭐ Η ΘΕΡΑΠΕΙΑ ΕΙΝΑΙ ΚΑΙ ΕΡΓΑΛΕΙΟ: επειδή το pho() σβήνει τα κενά, μια
   πολυλεκτική λέξη-κλειδί γραμμένη ΣΑΝ ΜΙΑ συμβολοσειρά («μεγαλη ιδεα»)
   απαιτεί ΓΕΙΤΝΙΑΣΗ, ενώ δύο ξεχωριστές απαιτούν απλώς παρουσία. */
(function () {
  var n = 0;
  I.UNITS.forEach(function (u) {
    u.skeleton.points.forEach(function (p, i) {
      p.must.forEach(function (e) {
        u.skeleton.points.forEach(function (q, j) {
          if (i === j) return;
          if (I.matched(e, q.detail)) {
            n++; console.log('  ✗ «' + e.k + '» ανάβει από το σημείο ' + (j + 1) + ' («' + q.label + '»)');
          }
        });
      });
    });
  });
  eq(n, 0, '⭐⭐ κανένα στοιχείο δεν ανάβει από ΑΛΛΟ σημείο της ίδιας ενότητας');
})();

