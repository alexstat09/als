function asWords(s) {
  return s.replace(/(\d+)(ού|ου|ός|ος|ό|ο|ή|η)/g, function (m, d, suf) { return (ORD[+d] && ORD[+d][suf]) || m; })
    .replace(/\d+/g, function (d) { return NUM[+d] || d; });
}

