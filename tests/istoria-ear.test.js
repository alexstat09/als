/* ── 7 · ΟΙ ΔΙΚΕΣ ΤΟΥ ΦΡΑΣΕΙΣ ──────────────────────────────────────── */
(function () {
  var u2 = I.unit('a2'), p = u2.skeleton.points[2], e = p.must[3];   /* εσωτερική αγορά */
  var mine = 'και δεν είχε κόσμο να αγοράσει μέσα στη χώρα';
  ok(!I.matched(e, mine), 'πριν: η δική του διατύπωση δεν πιάνεται');
  ok(I.matched(e, mine, [mine]), '⭐ μετά: με τη δική του φράση πιάνεται');
  ok(!I.matched(e, 'τελείως άλλο πράγμα', [mine]), 'η φράση δεν ανάβει σε άσχετο κείμενο');
  ok(!I.matched(e, mine, ['ναι']), '⚠️ πολύ κοντή φράση ΔΕΝ γίνεται δεκτή (παραθυράκι)');

  /* bestSentence ΔΙΑΛΕΓΕΙ από όσα είπε, δεν γράφει. */
  var heard = 'η χώρα δεν είχε πρώτες ύλες. και δεν είχε κόσμο να αγοράσει μέσα στη χώρα. τέλος.';
  var sen = I.bestSentence(heard, e.k);
  ok(heard.indexOf(sen) >= 0, '⭐ bestSentence επιστρέφει κομμάτι ΤΟΥ ΔΙΚΟΥ ΤΟΥ λόγου');
  ok(sen.length > 10, 'bestSentence: όχι κολόβωμα → «' + sen + '»');
  eq(I.bestSentence('', e.k), '', 'bestSentence: σιωπή δεν δίνει φράση');
  eq(I.bestSentence('άσχετα λόγια εντελώς', 'ζζζζζζ'), '', 'bestSentence: καμία σχέση → τίποτα');

  /* Οι φράσεις περνάνε σωστά μέσα από το gradeUnit. */
  var al = {}; al['2:3'] = [mine];
  var g0 = I.gradeUnit(u2, mine), g1 = I.gradeUnit(u2, mine, al);
  ok(g1.said === g0.said + 1, '⭐ gradeUnit δέχεται τις φράσεις του ανά στοιχείο');
  ok(!I.gradeUnit(u2, 'άσχετα', al).said, 'και δεν ανάβουν από μόνες τους');
})();

/* ── 8 · ⭐⭐ Ο ΜΕΤΑΓΡΑΦΕΑΣ ΔΕΝ ΠΕΤΑΕΙ ΛΟΓΙΑ ΤΟΥ ─────────────────────────
   ΑΥΤΟ ΕΙΝΑΙ Η ΣΗΜΑΝΤΙΚΟΤΕΡΗ ΔΙΟΡΘΩΣΗ ΤΗΣ als-v457 ΚΑΙ ΠΑΡΑΛΙΓΟ ΝΑ ΜΕΙΝΕΙ
   ΑΦΥΛΑΚΤΗ: έσβησα τη γραμμή για να δοκιμάσω αν δαγκώνει κάποιος έλεγχος, και
   πέρασαν και τα 34.  Ο Chrome κόβει τη συνεδρία στη ΣΙΩΠΗ — δηλαδή ακριβώς
   στις παύσεις ανάμεσα στα σημεία — και η φράση που είναι ακόμη «στον αέρα»
   χάνεται για πάντα αν δεν σωθεί ΠΡΙΝ την επανεκκίνηση.  Καμία assertion για
   λέξεις-κλειδιά δεν μπορεί να το δει: το κείμενο απλώς δεν φτάνει ποτέ. */
(function () {
  var fs = require('fs');
  var SRC = fs.readFileSync(path.join(__dirname, '..', 'istoria.html'), 'utf8');
  var m = SRC.match(/rec\.onend\s*=\s*function\s*\(\)\s*\{([\s\S]*?)\n      \};/);
  ok(!!m, 'βρέθηκε ο onend');
  var body = m ? m[1] : '';
  var flush = body.indexOf('heardFinal += \' \' + heardTmp');
  var start = body.indexOf('rec.start()');
  ok(flush >= 0, '⭐⭐ ο onend ΣΩΖΕΙ την ημιτελή φράση πριν σβηστεί');
  ok(flush >= 0 && start >= 0 && flush < start,
    '⭐⭐ και τη σώζει ΠΡΙΝ την επανεκκίνηση, όχι μετά');
  ok(/heardTmp\s*=\s*''/.test(body), 'και μηδενίζει το interim αφού το σώσει');

  /* Οι εκδοχές: ζητάμε πολλές ΚΑΙ τις διαβάζουμε. Το ένα χωρίς το άλλο
     είναι σταθερή αρχή 23 — γράφω μια σύμβαση και δεν τη διαβάζω. */
  ok(/rec\.maxAlternatives\s*=\s*ALTS/.test(SRC), 'ζητάμε πολλές εκδοχές του ίδιου ήχου');
  ok(/var ALTS = ([2-9])/.test(SRC), 'και είναι πράγματι πάνω από μία');
  /* ⚠️ Η ΙΔΙΟΤΗΤΑ, ΟΧΙ Η ΓΡΑΜΜΗ (μάθημα της als-v453): ένας φρουρός γραμμένος
     πάνω σε μία διατύπωση έχει τη ζωή της διατύπωσης, όχι του κανόνα. */
  ok(/r\[k\]\.transcript/.test(SRC) && /<\s*ALTS/.test(SRC),
    '⭐ ΚΑΙ ΤΙΣ ΔΙΑΒΑΖΟΥΜΕ ΟΛΕΣ, όχι μόνο την πρώτη');
  ok(/r\.length \|\| 1/.test(SRC),
    '⚠️ και μια μηχανή χωρίς length δίνει ΜΙΑ εκδοχή, ποτέ καμία');

  /* Σταθερή αρχή 10: ανοιχτό μικρόφωνο που δεν πιάνει τίποτα ΔΕΝ επιτρέπεται
     να μοιάζει με ένα που ακούει. */
  ok(/SILENCE_MS/.test(SRC) && /δεν έχω πιάσει λέξη/.test(SRC),
    '⭐ η σιωπή σε ανοιχτό μικρόφωνο λέει το όνομά της');
  ok(/clearInterval\(silenceTimer\)/.test(SRC), 'και ο μετρητής σβήνει όταν κλείνει το μικρόφωνο');

  /* Η απόδειξη: βλέπει ΑΚΡΙΒΩΣ τι έφτασε. */
  ok(/rc-tr-b/.test(SRC) && /Τι άκουσα/.test(SRC), '⭐ η σύνοψη δείχνει ολόκληρη τη μεταγραφή');
  ok(/\.rc-tr-b\{/.test(SRC) && /\.rc-said\{/.test(SRC),
    'σταθερή αρχή 12: οι νέες κλάσεις ΟΡΙΖΟΝΤΑΙ στο CSS');
  ok(/bestSentence\(sess\.heard/.test(SRC),
    '⭐ το «το είπα αυτό» ΔΙΑΛΕΓΕΙ από όσα είπε, δεν γράφει φράση');
})();

