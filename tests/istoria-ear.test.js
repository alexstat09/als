/* ── 3 · ⭐⭐ Η ΜΕΤΡΗΣΗ, ΚΛΕΙΔΩΜΕΝΗ ─────────────────────────────────── */
function homophone(s) {
  return s.replace(/ει|οι|υι/g, 'ι').replace(/η/g, 'ι').replace(/υ/g, 'ι')
    .replace(/ω/g, 'ο').replace(/αι/g, 'ε');
}
function splitWords(s) { return s.replace(/(\S{6})(\S{4,})/g, function (m, a, b) { return a + ' ' + b; }); }
var NUM = {
  1828: 'χίλια οκτακόσια είκοσι οκτώ', 1854: 'χίλια οκτακόσια πενήντα τέσσερα',
  1864: 'χίλια οκτακόσια εξήντα τέσσερα', 1881: 'χίλια οκτακόσια ογδόντα ένα',
  1911: 'χίλια εννιακόσια έντεκα', 15: 'δεκαπέντε', 43: 'σαράντα τρία',
  19: 'δέκατο ένατο', 20: 'εικοστό'
};
/* ⚠️ ΤΑ ΤΑΚΤΙΚΑ ΠΡΩΤΑ, ΚΑΙ ΜΕ ΤΗΝ ΠΤΩΣΗ ΤΟΥΣ.  Η πρώτη γραφή αυτού του
   αρχείου έκανε σκέτο `\d+` και παρήγαγε «δέκατο ένατοου αιώνα» — φράση που
   δεν λέει άνθρωπος.  Απέτυχε σωστά η προσομοίωση, όχι η μηχανή: και οι δύο
   αληθινές διατυπώσεις («δέκατου ένατου» και «19ου») πιάνονται.  Μια
   προσομοίωση που παράγει αδύνατα δεδομένα είναι φρουρός που κλαίει. */
var ORD = { 19: 'δέκατου ένατου', 20: 'εικοστού' };
function asWords(s) {
  return s.replace(/(\d+)(ου|ού|ό|ος|η)/g, function (m, d) { return ORD[+d] || m; })
    .replace(/\d+/g, function (d) { return NUM[+d] || d; });
}

