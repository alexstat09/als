/* ── 4 · ⭐ Ο ΤΟΝΟΣ ΞΕΧΩΡΙΖΕΙ ΤΑ ΟΜΟΗΧΑ ────────────────────────────── */
(function () {
  eq(EAR.pho('ἀγγέλλω'), EAR.pho('ἀγγελῶ'), 'ο ΗΧΟΣ των δύο είναι ίδιος (γι΄ αυτό χρειάζεται ο τόνος)');
  eq(EAR.stress('ἀγγέλλω'), 1, 'ἀγγέλλω: παραλήγουσα');
  eq(EAR.stress('ἀγγελῶ'), 0, 'ἀγγελῶ: λήγουσα');
  eq(EAR.stress('ἤγγειλα'), 2, 'ἤγγειλα: προπαραλήγουσα');
  eq(EAR.stress('αγγελω'), -1, 'άτονο = δεν ξέρω');
  ok(EAR.sameStress('ἀγγέλλω', 'αγγελω'), '⭐ άτονο ΔΕΝ κόβει σωστή απάντηση');
  ok(!EAR.sameStress('ἀγγέλλω', 'αγγελώ'), 'αλλά λάθος τόνος κόβει');

  var p = A.PAGES[0];
  function litAct(text) {
    var out = [];
    A.gradePage(p, text).cells.forEach(function (c) {
      if (c.vid !== 'aggello' || c.voice !== 'act') return;
      c.hits.forEach(function (h, i) { if (h) out.push(c.tense); });
    });
    return out;
  }
  eq(litAct('αγγέλλω').join(','), 'ens', '⭐⭐ λέγοντας ΜΟΝΟ τον ενεστώτα ανάβει ΜΟΝΟ ο ενεστώτας');
  eq(litAct('αγγελώ').join(','), 'mel', '⭐⭐ και ο μέλλοντας ΜΟΝΟ ο μέλλοντας');
  eq(litAct('αγγέλλω αγγελώ').join(','), 'ens,mel', 'και τα δύο μαζί, δύο');
  eq(litAct('αγγελω').join(','), 'ens,mel', '⚠️ άτονο: πιστώνονται και τα δύο, ποτέ κανένα');
})();

/* ── 5 · ⭐⭐ ΑΚΟΥΕΙ ΟΛΗ ΤΗ ΣΕΛΙΔΑ, ΟΠΩΣ ΤΗ ΓΡΑΦΕΙ Η ΜΗΧΑΝΗ ────────── */
function recital(p) {
  var out = [];
  A.verbsOf(p).forEach(function (v) {
    A.chains(v).forEach(function (c) {
      c.cells.forEach(function (cell) { if (cell.drill) out.push(cell.forms.join(' ')); });
    });
  });
  return out.join(' ');
}
/* ⚠️ ΡΕΑΛΙΣΤΙΚΗ προσομοίωση: τα δίψηφα με υ προφέρονται /v~f/, ΠΟΤΕ /i/, και
   το «ου» είναι ένας ήχος. Μια προσομοίωση που παράγει αδύνατα δεδομένα είναι
   φρουρός που κλαίει — η πρώτη γραφή αυτού του αρχείου το έκανε δύο φορές. */
function asr(s, voiced) {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '')
    .replace(/ου/g, '').replace(/ευ/g, voiced ? 'εβ' : 'εφ').replace(/αυ/g, voiced ? 'αβ' : 'αφ')
    .replace(/ει|οι|υι/g, 'ι').replace(/[ηυ]/g, 'ι').replace(/ω/g, 'ο').replace(/αι/g, 'ε')
    .replace(//g, 'ου');
}
function splitWords(s) { return s.replace(/(\S{6})(\S{4,})/g, function (m, a, b) { return a + ' ' + b; }); }

console.log('\nΑΡΧΑΙΑ — η ανάκληση των αρχικών χρόνων\n');
A.PAGES.forEach(function (p) {
  var R = recital(p), tot = A.gradePage(p, '').total;
  console.log('  σελίδα ' + p.n + ' · ' + A.verbsOf(p).length + ' ρήματα · ' +
    A.cellCount(p) + ' κελιά · ' + tot + ' τύποι');
  [
    ['όπως τη λες (πολυτονικά)', R, 1.00],
    ['μονοτονικά — ό,τι γράφει η φωνή', asr(R, false), 1.00],
    ['με «ευ» ηχηρό (αγορέβω)', asr(R, true), 0.97],
    ['και σπασμένες λέξεις', splitWords(asr(R, true)), 0.95]
  ].forEach(function (c) {
    var g = A.gradePage(p, c[1]);
    console.log('    ' + c[0].padEnd(34) + g.said + '/' + g.total + '  ' + Math.round(g.coverage * 100) + '%');
    ok(g.coverage >= c[2], 'ΑΝΑΚΛΗΣΗ «' + c[0] + '» σελίδα ' + p.n + ': ' +
      Math.round(g.coverage * 100) + '% (κατώφλι ' + Math.round(c[2] * 100) + '%)');
  });
});
console.log('');

