  ok(A.saidForm(H2, 'ἄγω'), 'λέγοντας «ἄγω» ανάβει το ἄγω');
  ok(!A.saidForm(H2, 'ἀγορεύω'), 'και ΔΕΝ ανάβει το ἀγορεύω');

