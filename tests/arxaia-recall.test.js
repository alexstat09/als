  ok(!A.saidForm(H1, 'ἄγω'), '⭐⭐ λέγοντας «ἀγορεύω» ΔΕΝ ανάβει το ἄγω');
  ok(A.saidForm(H1, 'ἀγορεύω'), 'αλλά ανάβει το ἀγορεύω');
  ok(A.saidForm(H1, 'ἠγόρευσα'), 'και ο αόριστός του');

