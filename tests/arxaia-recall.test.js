'use strict';

var path = require('path');
var A = require(path.join(__dirname, '..', 'arxaia-data.js'));
var EAR = require(path.join(__dirname, '..', 'greek-ear.js'));

var pass = 0, fail = 0;
function ok(cond, msg) { if (cond) { pass++; } else { fail++; console.log('  ✗ ' + msg); } }
function eq(a, b, msg) { ok(a === b, msg + '  (got ' + JSON.stringify(a) + ', want ' + JSON.stringify(b) + ')'); }

/* ── 1 · Η ΣΕΛΙΔΑ ΕΙΝΑΙ Η ΜΟΝΑΔΑ ────────────────────────────────────── */
ok(A.PAGES && A.PAGES.length >= 1, 'υπάρχει τουλάχιστον μία σελίδα');
A.PAGES.forEach(function (p) {
  ok(/^\d{4}-\d{2}-\d{2}$/.test(p.added), 'σελίδα ' + p.n + ' · έγκυρη ημερομηνία ανάθεσης');
  ok(!!p.range && !!p.id, 'σελίδα ' + p.n + ' · έχει ταυτότητα');
  ok(!!(p.simple && p.simple.length >= 3), '⭐ σελίδα ' + p.n + ' · έχει «με απλά λόγια»');
  ok(!!(p.free && p.free.length >= 3), '⭐ σελίδα ' + p.n + ' · έχει «τι βγαίνει μόνο του»');
  ok(!!A.page(p.id), 'σελίδα ' + p.n + ' · βρίσκεται με page()');
  /* Η σειρά ΔΕΝ είναι αλφαβητική, και δεν επιτρέπεται να χάνει ρήμα. */
  eq(A.verbsOf(p).length, p.order.length, 'σελίδα ' + p.n + ' · κάθε id της σειράς βρίσκει ρήμα');
  ok(A.cellCount(p) > 0, 'σελίδα ' + p.n + ' · έχει κελιά προς εξέταση');
});
/* Κάθε ρήμα του corpus ανήκει σε ΜΙΑ σελίδα — αλλιώς είναι αόρατο. */
(function () {
  var placed = {};
  A.PAGES.forEach(function (p) { p.order.forEach(function (id) { placed[id] = (placed[id] || 0) + 1; }); });
  A.VERBS.forEach(function (v) {
    eq(placed[v.id] || 0, 1, '⭐ το ' + v.lemma + ' ανήκει σε ΑΚΡΙΒΩΣ μία σελίδα');
  });
})();

