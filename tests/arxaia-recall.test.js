/* ── 9 · ⭐ Η ΣΕΛΙΔΑ ΤΗΡΕΙ ΤΟ ΣΧΗΜΑ ΤΗΣ ΙΣΤΟΡΙΑΣ ───────────────────── */
(function () {
  var fs = require('fs');
  var SRC = fs.readFileSync(path.join(__dirname, '..', 'arxaia.html'), 'utf8');
  /* ⚠️ Σταθερή αρχή 19: ο φρουρός δεν επιτρέπεται να κλαίει. Η πρώτη γραφή
     αυτού του ελέγχου σκάλωσε στο ΣΧΟΛΙΟ που εξηγεί ότι οι «12 ερωτήσεις»
     αφαιρέθηκαν. Ό,τι κρίνει τι ΒΛΕΠΕΙ ο χρήστης τρέχει χωρίς σχόλια. */
  var SEEN = SRC.replace(/<!--[\s\S]*?-->/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
  ok(/Για αύριο/.test(SEEN), '⭐ ανοίγει σε «ΓΙΑ ΑΥΡΙΟ», ποτέ σε μενού');
  ok(!/12 ερωτήσεις/.test(SEEN), '⭐ και ΟΧΙ σε «12 ερωτήσεις» — αυτό ήταν που τον μπέρδευε');
  ['Με απλά λόγια', 'Ο πίνακας', 'Τι βγαίνει μόνο του', 'Οι αλυσίδες'].forEach(function (l) {
    ok(SRC.indexOf(l) > 0, 'στρώση «' + l + '» υπάρχει');
  });
  ok(/Κλείσε το φυλλάδιο και πες το/.test(SRC), '⭐ η εξέταση είναι ΑΠΑΓΓΕΛΙΑ');
  ok(/greek-ear\.js/.test(SRC), 'φορτώνει το κοινό αυτί');
  ok(/λείπει το greek-ear|δεν φόρτωσε/.test(SRC), '⚠️ και το λέει αν λείψει (σταθερή αρχή 10)');
  /* Ο τίμιος περιορισμός ΓΡΑΜΜΕΝΟΣ ΣΤΗΝ ΟΘΟΝΗ, όχι μόνο σε σχόλιο. */
  ok(/ΠΟΙΟΣ είναι ο τύπος, όχι πώς γράφεται/.test(SRC),
    '⭐⭐ λέει στον χρήστη ότι η φωνή ΔΕΝ ελέγχει ορθογραφία');
  /* Το bug που έσβηνε λόγια του, ίδιο σε δύο σελίδες (σταθερή αρχή 15). */
  var m = SRC.match(/rec\.onend\s*=\s*function\s*\(\)\s*\{([\s\S]*?)\n      \};/);
  ok(!!m, 'βρέθηκε ο onend');
  if (m) {
    var flush = m[1].indexOf("heardFinal += ' ' + heardTmp"), start = m[1].indexOf('rec.start()');
    ok(flush >= 0 && start >= 0 && flush < start,
      '⭐⭐ σώζει την ημιτελή φράση ΠΡΙΝ την επανεκκίνηση, όπως η Ιστορία');
  }
  ok(/r\[k\]\.transcript/.test(SRC) && /r\.length \|\| 1/.test(SRC), 'κρατάει όλες τις εκδοχές');
  /* Η δήλωση δεν είναι μέτρηση. */
  var body = SRC.slice(SRC.indexOf('function doClaim'), SRC.indexOf('function undoClaim'));
  ok(body.indexOf('reviews') < 0 && body.indexOf('best') < 0,
    '⭐ το «Το ξέρω απέξω» ΔΕΝ αγγίζει σκάλα ούτε ακρίβεια');
})();

