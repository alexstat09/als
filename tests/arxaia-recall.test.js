  eq(cs.length, 2, 'το ἀγγέλλω έχει δύο φωνές');
  eq(cs[0].cells.length, 6, 'και έξι χρόνους στην ενεργητική');
  eq(cs[0].cells[0].forms[0], 'ἀγγέλλω', 'η αλυσίδα ξεκινά από τον ενεστώτα');
  eq(cs[0].cells[5].forms[0], 'ἠγγέλκειν', 'και τελειώνει στον υπερσυντέλικο');

  var ag = A.verb('agamai');
