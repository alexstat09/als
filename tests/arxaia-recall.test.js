/* ── 3 · ⚠️⚠️ Η ΠΑΓΙΔΑ: ΤΟ «ἄγω» ΚΡΥΒΕΤΑΙ ΜΕΣΑ ΣΤΟ «ἀγορεύω» ─────────── */
