/* ══════════════════════════════════════════════════════════════════════
   tests/arxaia-laptop.test.js — ΤΟ ΛΑΠΤΟΠ ΔΕΝ ΕΙΝΑΙ ΜΕΓΑΛΟ ΚΙΝΗΤΟ

   ⭐⭐⭐ ΓΙΑΤΙ ΥΠΑΡΧΕΙ. Δικά του λόγια, als-v507:
     «δεν κτλβαινω γιατι οτιδηποτε σου ζητω να φτιαχνεις παντα το κανεις
      σε μορφη κινητου και ασχημο… απο το λαπτοπ θα διαβαζω»

   Είχε δίκιο, και η αιτία ΔΕΝ ήταν γούστο — ήταν τρία μετρήσιμα λάθη που
   καμία λειτουργική βεβαίωση δεν βλέπει, γιατί η σελίδα δούλευε τέλεια:

     1. ΤΟ ΠΛΑΤΟΣ. `.ar-wrap` = 620px. Ο ΓΝΩΣΤΟΣ πήρε override 1240px στην
        als-v498· ο ΑΓΝΩΣΤΟΣ δεν το πήρε ποτέ. Λωρίδα μέσα σε μαύρο.
     2. ⛔ Η ΑΝΑΠΟΔΗ ΘΡΑΥΣΗ. Είχα γράψει `@media(min-width:900px)` για δύο
        στήλες. Το media query μετράει το VIEWPORT, ΟΧΙ τον γονέα — άρα σε
        λάπτοπ έσπαγε τη λωρίδα των 620px σε δύο στήλες των ~280px.
        ΧΕΙΡΟΤΕΡΟ από μία στήλη. Αυτό ήταν το «μορφή κινητού».
     3. ⛔ ΠΕΡΙΕΧΟΜΕΝΟ ΝΤΥΜΕΝΟ ΣΑΝ ΧΡΩΜΙΟ. Το `--au-faint` μετράει 2.98:1
        πάνω στο #050506 — κάτω από το 4.5:1 του WCAG AA — και το είχα
        δώσει στη ΦΡΑΣΗ ΤΟΥ ΦΥΛΛΑΔΙΟΥ, στις σημασίες των ρημάτων και στην
        εκφορά, στα 11.5-12.5px. Το πιο σημαντικό κείμενο της σελίδας ήταν
        το πιο δυσανάγνωστο.

   Αυτό το αρχείο τα κλειδώνει και τα τρία. Δεν ελέγχει «αν είναι ωραίο» —
   ελέγχει τα ΝΟΥΜΕΡΑ κάτω από το ωραίο.
   ══════════════════════════════════════════════════════════════════════ */
'use strict';
const fs = require('fs');
const path = require('path');
const ALS = path.resolve(__dirname, '..');

let pass = 0, fail = 0;
function ok(name, cond){ cond ? pass++ : fail++; console.log((cond ? '  ✓ ' : '  ✗ FAIL ') + name); }
function is(name, got, want){
  const good = String(got) === String(want);
  good ? pass++ : fail++;
  console.log((good ? '  ✓ ' : '  ✗ FAIL ') + name + (good ? '' : `\n      got ${got} · want ${want}`));
}
function section(s){ console.log('\n' + s); }

const PAGE = fs.readFileSync(path.join(ALS, 'arxaia.html'), 'utf8');
/* ⚠️ ΤΑ ΣΧΟΛΙΑ ΒΓΑΙΝΟΥΝ ΠΡΩΤΑ. Η πρώτη γραφή αυτού του τεστ «έβρισκε»
   ένα @media(min-width) που ήταν Η ΙΔΙΑ Η ΠΕΡΙΓΡΑΦΗ ΤΟΥ BUG μέσα σε
   σχόλιο. Ένα τεστ που διαβάζει τα σχόλιά του δεν ελέγχει τον κώδικα. */
const RAW = PAGE.slice(PAGE.indexOf('<style>'), PAGE.indexOf('</style>'));
const CSS = RAW.replace(/\/\*[\s\S]*?\*\//g, '');

/* ══ 1 · ΤΟ ΠΛΑΤΟΣ ═══════════════════════════════════════════════════ */
section('1 · ΟΙ ΔΥΟ ΚΟΣΜΟΙ ΕΧΟΥΝ ΤΟ ΙΔΙΟ ΠΛΑΤΟΣ ΚΑΙ ΤΗΝ ΙΔΙΑ ΘΡΑΥΣΗ');
const wide = sel => {
  const m = new RegExp(sel.replace(/[.#]/g, '\\$&') + '\\{[^}]*max-width:(\\d+)px').exec(CSS);
  return m ? +m[1] : null;
};
const gnW = wide('#gnWrap.ar-wrap'), agW = wide('#agWrap.ar-wrap');
ok('ο ΓΝΩΣΤΟΣ έχει πλάτος laptop', gnW >= 1100);
ok('⭐ ο ΑΓΝΩΣΤΟΣ ΤΟ ΕΧΕΙ ΚΙ ΑΥΤΟΣ (εδώ ήταν το bug)', agW >= 1100);
is('και είναι ΤΟ ΙΔΙΟ — δύο κόσμοι σε άλλο πλάτος είναι δύο κόσμοι να μάθεις', agW, gnW);

/* Το σημείο θραύσης ΤΩΝ ΣΤΗΛΩΝ πρέπει να είναι ΕΝΑ. (Άλλα, μικρότερα
   breakpoints για λεπτομέρειες τηλεφώνου είναι θεμιτά — εδώ ελέγχεται
   μόνο το σημείο όπου οι δύο κόσμοι μαζεύουν τις στήλες τους.) */
function collapseAt(colSel){
  const at = CSS.indexOf(colSel + '{ grid-template-columns:1fr');
  if (at < 0) return null;
  const before = CSS.slice(0, at);
  const m = [...before.matchAll(/@media\(max-width:(\d+)px\)/g)].pop();
  return m ? +m[1] : null;
}
const gnBp = collapseAt('#gnWrap .gn-cols'), agBp = collapseAt('#agWrap .ag-cols');
ok('ο ΓΝΩΣΤΟΣ μαζεύει τις στήλες του σε σημείο θραύσης', !!gnBp);
ok('ο ΑΓΝΩΣΤΟΣ επίσης', !!agBp);
is('⭐ και είναι ΤΟ ΙΔΙΟ σημείο', agBp, gnBp);

/* ══ 2 · Η ΑΝΑΠΟΔΗ ΘΡΑΥΣΗ ════════════════════════════════════════════ */
section('2 · ⛔ ΚΑΜΙΑ ΘΡΑΥΣΗ ΠΡΟΣ ΤΑ ΠΑΝΩ');
/* Ο κανόνας του project: η πλήρης όψη γράφεται ΠΡΩΤΑ, και το τηλέφωνο τη
   ΜΑΖΕΥΕΙ με `max-width`. Ένα `min-width` ανοίγει στήλες με βάση το
   VIEWPORT χωρίς να ξέρει τι πλάτος έχει ο γονέας — και έτσι γεννήθηκαν
   οι δύο στήλες των 280px μέσα σε λωρίδα 620px. */
is('κανένα @media(min-width) πουθενά στη σελίδα', (CSS.match(/@media[^{]*min-width/g) || []).length, 0);
ok('οι στήλες δηλώνονται σε ΠΛΗΡΕΣ πλάτος', /#agWrap \.ag-cols\{[^}]*grid-template-columns:1\.34fr \.86fr/.test(CSS));
ok('και μαζεύονται σε μία κάτω από τη θραύση', /@media\(max-width:1040px\)\{[\s\S]*?#agWrap \.ag-cols\{ grid-template-columns:1fr/.test(CSS));

/* ══ 3 · ΠΕΡΙΕΧΟΜΕΝΟ ≠ ΧΡΩΜΙΟ ════════════════════════════════════════ */
section('3 · ΟΤΙ ΔΙΑΒΑΖΕΤΑΙ ΕΧΕΙ ΑΝΤΙΘΕΣΗ ΚΑΙ ΜΕΓΕΘΟΣ');
/* --au-faint = rgba(245,242,236,.30) → 2.98:1 πάνω στο #050506.
   Επιτρέπεται ΜΟΝΟ σε ετικέτες/μετρητές. Κάθε λέξη που τη διαβάζει
   πρέπει να είναι --au-dim (7.11:1) ή --au-ivory (18.2:1). */
const CONTENT = [
  '#synLesson .cmp-src',    /* Η ΦΡΑΣΗ ΤΟΥ ΦΥΛΛΑΔΙΟΥ — το πιο σημαντικό κείμενο */
  '#synLesson .cmp-v',
  '#synLesson .pl-i i',     /* η σημασία του ρήματος */
  '#synLesson .pl-i .ex',
  '#synLesson .tr-l .nt',   /* η εκφορά της πρότασης */
  '#synLesson .tr-bn',
  '#synLesson .sy-note p',
  '#synLesson .sy-sw .sg',
  '#synLesson .sy-gap',
  '#synLesson .sy-src',
  '#synLesson .sy-done p',
  '#agWrap .sh-note'
];
function rule(sel){
  const at = CSS.indexOf(sel + '{');
  if (at < 0) return null;
  return CSS.slice(at, CSS.indexOf('}', at));
}
let faint = [], tiny = [];
CONTENT.forEach(sel => {
  const r = rule(sel);
  if (r == null){ fail++; console.log('  ✗ FAIL λείπει ο κανόνας ' + sel); return; }
  if (/--au-faint/.test(r)) faint.push(sel);
  const fs2 = /font-size:([\d.]+)px/.exec(r);
  if (fs2 && +fs2[1] < 13.5) tiny.push(sel + ' @' + fs2[1] + 'px');
});
is('⛔ κανένα κείμενο ανάγνωσης στο --au-faint (2.98:1)', faint.join(', '), '');
is('⛔ κανένα κείμενο ανάγνωσης κάτω από 13.5px', tiny.join(', '), '');
ok('η φράση του φυλλαδίου είναι πλέον 14.5px σε --au-dim',
   /#synLesson \.cmp-src\{[^}]*font-size:14\.5px[\s\S]*?--au-dim/.test(CSS));

/* ══ 4 · ΤΟ ΜΕΤΡΟ ΑΝΑΓΝΩΣΗΣ ══════════════════════════════════════════ */
section('4 · Η ΠΡΟΖΑ ΔΕΝ ΤΕΝΤΩΝΕΤΑΙ ΣΤΑ 1180px');
/* Η μία απόφαση της als-v500: κάθε στρώση παίρνει ΤΟ ΔΙΚΟ ΤΗΣ πλάτος.
   Η πρόζα μένει σε μέτρο ανάγνωσης· η αντιπαραβολή παίρνει όλο το πλάτος,
   γιατί εκεί είναι όλο το κέρδος του λάπτοπ. */
[['#synLesson .sy-lead', 70], ['#synLesson .sy-note p', null], ['#synLesson .sy-mine', 78],
 ['#synLesson .sy-gap', 78], ['#agWrap .ar-foot', 78]].forEach(([sel, max]) => {
  /* Το μέτρο μπορεί να ζει στον ΓΟΝΕΑ (`.sy-note` αντί για `.sy-note p`)
     — αυτό είναι σωστό, αρκεί να υπάρχει κάπου στην αλυσίδα. */
  const own = rule(sel), parent = sel.includes(' p') ? rule(sel.replace(' p', '')) : null;
  const m = /max-width:(\d+)ch/.exec(own || '') || /max-width:(\d+)ch/.exec(parent || '');
  ok(sel + ' έχει μέτρο ανάγνωσης' + (m ? ' (' + m[1] + 'ch)' : ''), !!m && +m[1] <= 80);
});
ok('η ΑΝΤΙΠΑΡΑΒΟΛΗ όμως ΔΕΝ περιορίζεται — παίρνει όλο το πλάτος',
   !/#synLesson \.cmp\{[^}]*max-width/.test(CSS));
ok('και κυλάει μέσα στο κουτί της αντί να σπρώξει το body',
   /#synLesson \.cmp\{[^}]*overflow-x:auto/.test(CSS));
ok('η εξάσκηση μένει σε στήλη ανάγνωσης', /#synLesson \.dr\{ max-width:6\d\dpx/.test(CSS));

/* ══ 5 · ΑΠΑΓΟΡΕΥΜΕΝΑ ΣΧΗΜΑΤΑ ════════════════════════════════════════ */
section('5 · ΤΑ ΑΝΤΑΝΑΚΛΑΣΤΙΚΑ ΠΟΥ ΔΕΝ ΜΠΑΙΝΟΥΝ');
const AGCSS = CSS.slice(CSS.indexOf('#agWrap.ar-wrap{'));
/* Πλαϊνή χρωματιστή ρίγα: το πιο κοινό διακοσμητικό αντανακλαστικό, δεν
   σημαίνει τίποτα, και η ίδια σήμανση γίνεται με πλήρες περίγραμμα. */
is('⛔ καμία πλαϊνή ρίγα (border-left > 1px ως χρώμα)',
   (AGCSS.match(/border-left(-width)?:\s*(?![01]px)\d+px/g) || []).join(', '), '');
is('⛔ κανένα gradient σε κείμενο', (AGCSS.match(/background-clip:\s*text/g) || []).length, 0);
/* Οι διακόπτες ήταν έξι πανομοιότυπα κουτάκια — το τεμπέλικο σχήμα. */
ok('οι διακόπτες είναι τυπογραφία σε κολόνες, όχι πλέγμα από κουτιά',
   /#synLesson \.sw-g\{ columns:2/.test(AGCSS) && !/\.sw-g\{[^}]*grid-template-columns/.test(AGCSS));
ok('και δεν είναι κουτιά', !/#synLesson \.sy-sw\{[^}]*border-radius/.test(AGCSS));
ok('υπάρχει εναλλακτική για prefers-reduced-motion',
   /@media \(prefers-reduced-motion: reduce\)/.test(AGCSS));

/* ══ 6 · Η ΑΝΤΙΣΤΟΙΧΙΑ ΔΙΑΒΑΖΕΤΑΙ ΣΑΝ ΒΙΒΛΙΟ (als-v523) ══════════════
   Δικά του: «το background του κάπως για σάιτ ιστοσελίδα παρά για
   διάβασμα». Δεν ήταν γούστο — ήταν τρία μετρήσιμα λάθη, και αυτή η
   ενότητα τα κλειδώνει ώστε να μην ξαναγυρίσουν σιωπηλά. */
section('6 · Η ΑΝΤΙΣΤΟΙΧΙΑ ΕΙΝΑΙ ΣΕΛΙΔΑ, ΟΧΙ ΚΑΡΤΕΣ');
{
  /* ⚠️⚠️ ΤΟ `rule()` ΤΟΥ ΑΡΧΕΙΟΥ ΔΕΝ ΚΑΝΕΙ ΕΔΩ, ΚΑΙ ΤΟ ΕΔΕΙΞΕ Η ΑΠΟΤΥΧΙΑ.
     Κάνει `indexOf('.al-a{')`, και το `#gnLesson .al-a{` ΠΕΡΙΕΧΕΙ αυτή τη
     συμβολοσειρά — και γράφεται ΠΙΟ ΠΑΝΩ στο αρχείο. Άρα το «στενό» και το
     «λάπτοπ» διάβαζαν ΤΟΝ ΙΔΙΟ κανόνα, και τρεις σωστές γραμμές κοκκίνιζαν.
     Σταθ. 30: πριν πιστέψεις την αποτυχία, έλεγξε το όργανο. Ο `own()`
     απαιτεί ΟΡΙΟ ΚΑΝΟΝΑ πριν τον επιλογέα, οπότε δεν μπορεί να πιάσει
     κανόνα του οποίου ο επιλογέας απλώς τελειώνει έτσι. */
  const own = sel => {
    const m2 = new RegExp('(?:^|[};])\\s*' + sel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\{([^}]*)')
      .exec(CSS);
    return m2 ? m2[1] : '';
  };
  const per  = own('.al-per');
  const perW = rule('#gnLesson .al-per') || '';
  const a    = own('.al-a');
  const m    = own('.al-m');
  const aW   = rule('#gnLesson .al-a') || '';
  const mW   = rule('#gnLesson .al-m') || '';
  const num  = n => { const x = /font-size:([\d.]+)px/.exec(n); return x ? +x[1] : null; };

  /* ⛔ ΤΟ ΛΑΘΟΣ ΠΟΥ ΠΟΝΑΕΙ: η ΜΕΤΑΦΡΑΣΗ είναι αυτό που λέει απέξω, και
     ήταν 14.5px δίπλα σε αρχαίο 19.5px — το πιο σημαντικό κείμενο της
     οθόνης ήταν το πιο μικρό. Δεν απαιτώ να είναι ΜΕΓΑΛΥΤΕΡΗ· απαιτώ να
     μην είναι δεύτερης κατηγορίας. */
  ok('η μετάφραση δεν είναι μικρότερη από 15px (στενό)',  num(m)  !== null && num(m)  >= 15);
  ok('η μετάφραση δεν είναι μικρότερη από 15px (λάπτοπ)', num(mW) !== null && num(mW) >= 15);
  is('⛔ η μετάφραση ΔΕΝ είναι στο --au-dim — είναι το κύριο κείμενο',
     /--au-dim/.test(m) ? 'είναι' : '', '');

  /* ⭐⭐ als-v528 — ΕΔΩ ΑΛΛΑΞΕ Η ΑΠΟΦΑΣΗ, ΚΑΙ ΤΗΝ ΑΛΛΑΞΕ ΕΚΕΙΝΟΣ.
     Η als-v523 απαιτούσε «η μετάφραση όχι δεύτερης κατηγορίας» και η
     als-v526 το έκανε ΙΣΟΤΗΤΑ (18/18, ίδιο μελάνι). Αφού όμως δοκίμασε
     ολόκληρη την 3η ενότητα σε artifact με ιεραρχία — αρχαίο 23px σε
     πλήρες μελάνι, μετάφραση 18px πιο ήσυχη — τα λόγια του ήταν «μ'
     αρέσει απίστευτα πιο πολύ… ΤΟ ΑΓΑΠΑΩ ΕΤΣΙ».
     ⚠️ Ο ΦΡΟΥΡΟΣ ΔΕΝ ΣΒΗΝΕΤΑΙ, ΑΛΛΑΖΕΙ ΔΙΑΤΥΠΩΣΗ: ο σκοπός του ήταν και
     παραμένει «η μετάφραση να μένει ΑΝΑΓΝΩΣΙΜΗ». Δεν το μετράει πια ως
     ισότητα — το μετράει ως ΚΑΤΩΦΛΙ: ποτέ κάτω από .62 διαφάνεια, που
     πάνω στο #050506 είναι 7,07:1, δηλαδή ακριβώς το σκαλί που είδε και
     ενέκρινε στο artifact (6,97:1 πάνω στο #0E1214 του). */
  var alpha = n => { const x = /color:\s*rgba\(245,\s*242,\s*236,\s*(\.\d+)\)/.exec(n);
                     return x ? +x[1] : (/--au-ivory/.test(n) ? 1 : null); };
  ok('η μετάφραση μένει πάνω από το 7:1 (στενό)',  alpha(m)  !== null && alpha(m)  >= 0.62);
  ok('η μετάφραση μένει πάνω από το 7:1 (λάπτοπ ή κληρονομιά)',
     alpha(mW) === null || alpha(mW) >= 0.62);
  ok('το αρχαίο είναι η ΜΕΓΑΛΥΤΕΡΗ φωνή (λάπτοπ)',
     num(aW) !== null && num(mW) !== null && num(aW) > num(mW));

  /* ⭐ ΜΙΑ ΟΙΚΟΓΕΝΕΙΑ ΓΙΑ ΤΙΣ ΔΥΟ ΣΤΗΛΕΣ: δύο διαφορετικές διαβάζονταν
     ως «κείμενο ‖ διεπαφή» αντί για ένα κείμενο σε δύο φωνές. */
  /* ⭐ als-v528: ΔΥΟ ΣΤΟΙΒΕΣ, ΚΑΙ ΟΙ ΔΥΟ ΔΗΛΩΜΕΝΕΣ. Το αρχαίο πάει στη
     GFS Didot (`--ar-anc`), η νέα γλώσσα μένει στην Alegreya (`--ar-gr`).
     Δεν είναι «δύο τυχαίες οικογένειες» — είναι δύο κείμενα με 2.300
     χρόνια απόσταση, και η βεβαίωση απαιτεί να είναι ΑΥΤΕΣ οι δύο. */
  ok('το αρχαίο είναι στη στοίβα του αρχαίου', /--ar-anc/.test(a));
  ok('η μετάφραση είναι στη στοίβα της νέας γλώσσας', /--ar-gr/.test(m) && !/--ar-anc/.test(m));
  ok('η στοίβα του αρχαίου ξεκινάει από GFS Didot',
     /--ar-anc:\s*"GFS Didot"/.test(CSS));
  is('⛔ καμία Georgia στην αντιστοιχία (als-v504)',
     (( a + m ).match(/Georgia/gi) || []).join(''), '');

  /* ⛔ ΟΙ ΚΑΡΤΕΣ. Έντεκα πανομοιότυπα πλαίσια = «σάιτ». */
  is('⛔ η περίοδος δεν έχει φόντο', (per.match(/background/g) || []).join(''), '');
  is('⛔ η περίοδος δεν έχει radius (στενό)', (per.match(/border-radius:\s*(?!0)/g) || []).join(''), '');
  ok('⛔ ούτε στο λάπτοπ', !/border-radius:\s*(?!0)[\d]/.test(perW));
  ok('⛔ και κανένα κάθετο διαχωριστικό — τη δουλειά την κάνει κενό',
     !/border-right:\s*1px/.test(aW) && /column-gap:\s*\d+px/.test(perW));

  /* ⚠️ Ο ΔΙΑΧΩΡΙΣΤΗΣ ΜΠΑΙΝΕΙ ΑΝΑΜΕΣΑ. Το `:last-of-type` ΔΕΝ δουλεύει
     εδώ (μετά τις περιόδους ακολουθεί το `.al-note`, που είναι κι αυτό
     `div`) — το έπιασε η μέτρηση, όχι το μάτι. */
  ok('ο διαχωριστής είναι αδελφικός `.al-per + .al-per`', !!own('.al-per + .al-per'));
  is('⛔ κανένα :last-of-type στις περιόδους',
     (CSS.match(/\.al-per:last-of-type/g) || []).join(''), '');

  /* ⛔ Λέξη χωρίς ζευγάρι είναι ΑΚΟΜΗ λέξη του κειμένου (ήταν 2.38:1). */
  is('⛔ οι λέξεις χωρίς ζευγάρι δεν είναι στο --au-faint',
     /--au-faint/.test(rule('.al-x') || '') ? 'είναι' : '', '');

  /* Το «γιατί» είναι κείμενο ανάγνωσης, όχι λεζάντα (σταθ. 52). */
  ok('το «γιατί» είναι ≥13.5px', num(rule('.al-why') || '') >= 13.5);

  /* ══ als-v526 — ΤΟ ΥΨΟΣ ΓΡΑΜΜΗΣ ΚΑΙ Η ΦΟΡΑ ΤΗΣ ΙΕΡΑΡΧΙΑΣ ═════════
     Δικά του, αφού διάβασε ολόκληρο τεστ με το χέρι: η δομή του artifact
     «ηταν πολυ πιο προσιτη για διαβασμα». Δεν ήταν γούστο — ήταν δύο
     νούμερα, και κλειδώνονται εδώ ώστε να μη γυρίσουν σιωπηλά. */
  const lh = n => { const x = /line-height:([\d.]+)/.exec(n); return x ? +x[1] : null; };

  /* ⛔ ΤΟ 1.95. Στα 18-19px αφήνει ~37px κενό: οι γραμμές γίνονται λωρίδες
     και το μάτι χάνει την επιστροφή στην αρχή της επόμενης. Το όριο είναι
     1.7 — πάνω από εκεί δεν είναι πια παράγραφος. */
  ok('το αρχαίο δεν ξεπερνάει το 1.7 (στενό)',  lh(a)  !== null && lh(a)  <= 1.7);
  ok('η μετάφραση δεν ξεπερνάει το 1.7 (στενό)', lh(m)  !== null && lh(m)  <= 1.7);
  ok('το αρχαίο δεν ξεπερνάει το 1.7 (λάπτοπ)',  lh(aW) !== null && lh(aW) <= 1.7);
  ok('η μετάφραση δεν ξεπερνάει το 1.7 (λάπτοπ)', lh(mW) !== null && lh(mW) <= 1.7);

  /* ⛔⛔ Η ΑΝΑΠΟΔΗ ΙΕΡΑΡΧΙΑ. Το αρχαίο καθόταν στο .82 (12,07:1) ενώ η
     μετάφραση στο 1.0 (18,13:1) — ΑΥΤΟ ΠΟΥ ΜΕΛΕΤΑΕΙ ήταν πιο αχνό από το
     βοήθημα. Η βεβαίωση αρνείται το ΠΡΟΤΥΠΟ (οποιοδήποτε ξεθώριασμα),
     όχι μια συγκεκριμένη τιμή — σταθ. 44: μια βεβαίωση που ζητάει
     «διαφορετικό από .82» δεν δαγκώνει όταν γίνει .84. */
  is('⛔ το αρχαίο ΔΕΝ είναι ξεθωριασμένο',
     (a.match(/color:\s*rgba\([^)]*,\s*\.\d+\s*\)/g) || []).join(''), '');
  ok('το αρχαίο είναι σε --au-ivory, όπως και η μετάφραση', /--au-ivory/.test(a));
  /* (Η ισότητα μεγεθών έφυγε στην als-v528 — δες την ενότητα 6.) */

  /* ⭐ Η ΓΡΑΜΜΑΤΟΣΕΙΡΑ ΣΩΜΑΤΟΣ ΜΠΡΟΣΤΑ. Η GFS Didot έχει πλήρες πολυτονικό
     (233/233, als-v504) αλλά είναι σχεδιασμένη για τίτλους· μένει ΔΕΥΤΕΡΗ
     ως δίχτυ, ποτέ πρώτη. */
  const stack = /--ar-gr:([^;]+);/.exec(CSS);
  ok('η στοίβα ξεκινάει από Alegreya', !!stack && /^\s*"Alegreya"/.test(stack[1]));
  ok('και κρατάει την GFS Didot από πίσω', !!stack && /GFS Didot/.test(stack[1]));

  /* ⛔⛔ Η GEORGIA ΔΕΝ ΞΑΝΑΜΠΑΙΝΕΙ ΑΠΟ ΤΗΝ ΠΙΣΩ ΠΟΡΤΑ. Το `--au-serif`
     ΟΡΙΖΕΤΑΙ στο aurora.css ως «Instrument Serif», Georgia, Times — και η
     Instrument Serif έχει ΜΗΔΕΝ ελληνικά γλυφά, άρα κάθε ελληνικός τίτλος
     που το ζητάει τυπώνεται στη Georgia, που έχει ΜΗΔΕΝ πολυτονικά.
     Ένας τίτλος με περισπωμένη έσπαγε σε δύο γραμματοσειρές. */
  is('⛔ κανένας κανόνας της σελίδας δεν ζητάει --au-serif',
     (CSS.match(/var\(--au-serif/g) || []).length ? 'ζητάει' : '', '');
}

