section('κάθε κελί παράγει ερώτηση, και η απάντηση δείχνει σωστά');
function seeded(n) { let s = n; return () => (s = (s * 1103515245 + 12345) % 2147483648) / 2147483648; }
T.CELLS.forEach(c => {
  let made = 0, broken = 0;
  for (let i = 1; i <= 60; i++) {
    const q = T.question(c.id, seeded(i * 7 + 3));
    if (!q) continue;
    made++;
    if (!q.opts || q.opts.length < 2) broken++;
    if (q.ans == null || q.ans < 0 || q.ans >= q.opts.length) broken++;
    if (new Set(q.opts).size !== q.opts.length) broken++;   // διπλή επιλογή = δύο σωστές
    if (!q.why) broken++;
  }
  is(c.id + ' · παράγει ερωτήσεις', made > 0, true);
  is(c.id + ' · καμία σπασμένη', broken, 0);
});

section('η σωστή επιλογή είναι όντως η σωστή γραφή');
