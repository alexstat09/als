const byWord = {};
T.WORDS.forEach(e => { byWord[e.w.normalize('NFC')] = e; });

section('κάθε λέξη του πίνακα υπάρχει στο corpus');
const missing = HAND.map(r => r[0]).filter(w => !byWord[w.normalize('NFC')]);
is('καμία λέξη του πίνακα δεν λείπει', missing, []);

section('συλλαβές · θέση τόνου · είδος · πνεύμα · ονομασία · ποσότητες');
HAND.forEach(row => {
  const [w, n, idx, type, breath, name, ult, pen] = row;
  const e = byWord[w.normalize('NFC')];
  if (!e) return;
  const a = T.analyze(e.w);
  is(w + ' · συλλαβές', a.n, n);
  is(w + ' · θέση τόνου', a.accIdx, idx);
  is(w + ' · είδος τόνου', a.accType, type);
  is(w + ' · πνεύμα', a.breath, breath);
  is(w + ' · ονομασία', T.nameOf(e), name);
  is(w + ' · λήγουσα', T.quantity(e, 1), ult);
  is(w + ' · παραλήγουσα', T.quantity(e, 2), pen);
});

