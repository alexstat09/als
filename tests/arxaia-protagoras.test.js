function scan(re, what) {
  var m, n = 0;
  while ((m = re.exec(page)) !== null) {
    var txt = m[1].replace(/<[^>]+>/g, '');
    (txt.match(/\d+(?:\/\d+)?/g) || []).forEach(function (num) {
      n++;
      ok(SRC_NUMS[num] === 1 || COUNTED[num] !== undefined,
        '⛔ ΤΟ « ' + num + ' » ΣΤΟ ' + what + ' ΔΕΝ ΥΠΑΡΧΕΙ ΣΤΟ ΒΙΒΛΙΟ (ούτε ως μέτρημα).\n' +
        '      Πλαίσιο: «' + txt + '»');
    });
  }
  ok(n > 0, 'βρέθηκαν νούμερα στο ' + what);
  return n;
}
