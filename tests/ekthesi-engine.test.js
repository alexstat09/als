section('cue');
is('cue 0 · μόνο το σχήμα', E.cue('ανίδεος', 0), '······ς');
is('cue 1 · πρώτο γράμμα',  E.cue('ανίδεος', 1), 'α·····ς');
is('cue 3 · τρία γράμματα', E.cue('ανίδεος', 3), 'ανί···ς');
is('cue σε δίγραμμη λέξη',  E.cue('ως', 0),      '·ς');
is('cue σε μονογράμματη',   E.cue('α', 0),       '·');
is('cue κενό',              E.cue('', 0),        '');
{
  /* Το νήμα ΠΟΤΕ δεν αποκαλύπτει ολόκληρη τη λέξη όσο μένει γράμμα κρυφό,
     και ΠΑΝΤΑ κρατάει το μήκος — που είναι μέρος του ερεθίσματος. */
  const bad = [];
  D.ALL.forEach(c => c.groups.forEach(g => g.items.forEach(it => {
    const w = it.w;
    for (let k = 0; k < w.length - 1; k++) {
      const q = E.cue(w, k);
      if (q.length !== w.length) bad.push(w + '@' + k + ' μήκος');
      if (q.indexOf('·') < 0) bad.push(w + '@' + k + ' χωρίς κρυφό');
    }
  })));
  is('το νήμα κρατάει μήκος και κρύβει', bad, []);
}

