/* ══ 9 · ⭐⭐ ΤΑ ΔΥΟ ΠΑΚΕΤΑ ΤΗΣ ΕΙΣΑΓΩΓΗΣ ═══════════════════════════════
   Η εντολή ήταν ρητή: «ακριβώς όπως είναι, χωρίς καμία αλλαγή». Δύο
   αυτοτελείς σελίδες, αντιγραμμένες με `cp` — ΟΧΙ ξαναγραμμένες, γιατί
   ξαναγραμμένες θα σήμαινε ελληνικά περασμένα από τα χέρια μου.

   ⚠️ ΓΙΑΤΙ HASH ΚΑΙ ΟΧΙ «ΥΠΑΡΧΕΙ ΤΟ ΑΡΧΕΙΟ». Ένα «υπάρχει» δεν πιάνει τη
   μόνη αποτυχία που φοβάμαι εδώ: κάποια μέρα κάποιος (πιθανότατα εγώ)
   «διορθώνει» μια φράση μέσα τους. Το sha256 το κάνει αδύνατο να περάσει
   αθόρυβα. Η ΜΟΝΗ επιτρεπτή διαφορά είναι η γραμμή «← Αρχαία», που
   αφαιρείται πριν το hash — άρα και αυτή είναι ΔΗΛΩΜΕΝΗ, όχι κρυφή.

   ⛔ ΚΑΙ Ο ΤΡΙΤΟΣ ΕΛΕΓΧΟΣ ΕΙΝΑΙ Ο ΛΟΓΟΣ ΠΟΥ ΕΓΙΝΕ ΟΛΗ Η ΑΛΛΑΓΗ: τα
   πακέτα ΔΕΝ γράφουν πουθενά. Καμία πρόοδος, καμία προθεσμία, κανένας
   βαθμός. Αν κάποτε μπει `localStorage` εκεί μέσα, η εισαγωγή έγινε ξανά
   κάτι που «χρωστάς» — και αυτό ήταν ακριβώς το παράπονο. */
(function () {
  var fs = require('fs'), crypto = require('crypto');
  PACKS.forEach(function (pk) {
    var abs = path.join(__dirname, '..', pk.file);
    if (!fs.existsSync(abs)) { ok(false, 'λείπει το πακέτο ' + pk.file); return; }
    var raw = fs.readFileSync(abs, 'utf8');

    /* Η μία δηλωμένη προσθήκη, και ΑΚΡΙΒΩΣ μία. */
    var backs = raw.split('\n').filter(function (l) { return l.indexOf('href="arxaia.html"') >= 0; });
    eq(backs.length, 1, pk.file + ': ακριβώς μία γραμμή επιστροφής «← Αρχαία»');

    var stripped = raw.split('\n').filter(function (l) { return l.indexOf('href="arxaia.html"') < 0; }).join('\n');
    var sum = crypto.createHash('sha256').update(stripped, 'utf8').digest('hex');
    eq(sum, pk.sha,
      '⛔ ΤΟ ΠΑΚΕΤΟ ' + pk.file + ' ΑΛΛΑΞΕ. Μπήκε αυτούσιο κατόπιν ρητής εντολής.\n' +
      '      Αν η αλλαγή είναι σκόπιμη, ΑΥΤΟΣ είναι ο νέος hash — και θέλει τη δική του κουβέντα.');

    ok(raw.indexOf('localStorage') < 0, pk.file + ': ⛔ δεν αποθηκεύει τίποτα — καμία πρόοδος, κανένας βαθμός');
    ok(raw.indexOf('arx:gn') < 0, pk.file + ': δεν αγγίζει το κλειδί του Γνωστού');
    ok(/<html lang="el">/.test(raw), pk.file + ': είναι αυτοτελής σελίδα στα ελληνικά');

    var sw = fs.readFileSync(path.join(__dirname, '..', 'sw.js'), 'utf8');
    ok(sw.indexOf("'" + pk.file + "'") > 0, pk.file + ': είναι στο SW CORE — αλλιώς πεθαίνει offline');
  });

  /* ⭐ ΚΑΙ Η ΠΑΛΙΑ ΕΙΣΑΓΩΓΗ ΔΕΝ ΧΑΘΗΚΕ.  Η μεταγραφή είναι δουλειά ΤΟΥ
     πάνω σε χαρτί που δεν κατεβαίνει από πουθενά — αν σβηστεί, σβήστηκε
     για πάντα.  Το «αρχειοθετήθηκε» πρέπει να αποδεικνύεται, όχι να
     υπόσχεται. */
  var arc = path.join(__dirname, '..', 'archive', 'arxaia-gnosto-eisagogi.js');
  var src = path.join(__dirname, '..', 'archive', 'arxaia-gnosto-eisagogi.source.txt');
  ok(fs.existsSync(arc), 'το corpus της εισαγωγής σώζεται στο archive');
  ok(fs.existsSync(src), 'η μεταγραφή του σώζεται στο archive');
  if (fs.existsSync(arc)) {
    var a = fs.readFileSync(arc, 'utf8');
    eq((a.match(/id: 'gn\d'/g) || []).length, 6, 'και είναι και οι έξι ενότητες');
    ok(a.indexOf('mine:') > 0, 'μαζί με τις χειρόγραφες σημειώσεις του');
  }
  if (fs.existsSync(src)) {
    /* ⚠️ ΟΞΕΙΑ, ΟΧΙ ΒΑΡΕΙΑ, ΚΑΙ ΕΙΝΑΙ ΣΚΟΠΙΜΟ. Το αρχείο κρατάει τη
       μεταγραφή ΤΟΥ ΑΔΙΟΡΘΩΤΗ — «Ἕν οἶδα», όπως την έγραψε. Η διόρθωση σε
       βαρεία ζούσε στο corpus, όχι στην πηγή. Ένα αρχείο που «διορθώνει»
       ό,τι φυλάει δεν είναι αρχείο. */
    ok(fs.readFileSync(src, 'utf8').indexOf('Ἕν οἶδα, ὅτι οὐδὲν οἶδα.') > 0,
      'και η μεταγραφή είναι η δική του, ΑΔΙΟΡΘΩΤΗ');
  }
})();

console.log('\n  ' + pass + ' πέρασαν, ' + fail + ' απέτυχαν\n');
if (fail) process.exit(1);
