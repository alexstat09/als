/* ══ 5 · Η ΒΑΘΜΟΛΟΓΗΣΗ ΛΕΕΙ ΤΗΝ ΑΛΗΘΕΙΑ ════════════════════════════════ */
(function () {
  var u = GN.unit('gk1');

  /* Σιωπή = 0. Ποτέ «πέρασες επειδή δεν είπες τίποτα». */
  eq(GN.gradeUnit(u, '').coverage, 0, 'σιωπή → 0%');
  eq(GN.gradeUnit(u, '   ').coverage, 0, 'κενά → 0%');

  /* Μία λέξη ΔΕΝ ανάβει σημείο — αυτό ήταν το bug της als-v452.
     ⚠️ Η λέξη πρέπει να ΥΠΑΡΧΕΙ στην ενότητα, αλλιώς ο έλεγχος γίνεται
     τετριμμένος: το 0% μιας άσχετης λέξης δεν αποδεικνύει τίποτα για το
     αν μια ΣΧΕΤΙΚΗ λέξη ολοκληρώνει σημείο. */
  var one = GN.gradeUnit(u, 'σελήνης');
  ok(one.coverage > 0 && one.coverage < 0.2, 'μία λέξη → ελάχιστο, ποτέ πλήρες σημείο (' + Math.round(one.coverage * 100) + '%)');
  ok(one.points.every(function (gp) { return gp.full === false; }),
    'μία λέξη δεν ολοκληρώνει ΚΑΝΕΝΑ σημείο');

  /* Ολόκληρο το κείμενο, διαβασμένο δυνατά, περνάει. */
  var all = GN.gradeUnit(u, GN.bodyOf(u) + ' ' + u.skeleton.points.map(function (p) {
    return p.must.map(function (m) { return m.k; }).join(' ');
  }).join(' '));
  ok(all.coverage >= GN.PASS, 'ολόκληρη η απαγγελία περνάει τη σκάλα (' + Math.round(all.coverage * 100) + '%)');

  /* Το ίδιο για ΚΑΘΕ ενότητα: αν το ίδιο της το κείμενο δεν την περνάει,
     τα `say` της είναι λάθος και θα τον έκοβαν ενώ τα λέει σωστά. */
  GN.UNITS.forEach(function (x) {
    var said = GN.bodyOf(x) + ' ' + x.skeleton.points.map(function (p) {
      return p.detail + ' ' + p.must.map(function (m) { return m.k; }).join(' ');
    }).join(' ');
    var g = GN.gradeUnit(x, said);
    ok(g.coverage >= GN.PASS,
      x.id + ': η ίδια της η ύλη περνάει τη σκάλα (' + Math.round(g.coverage * 100) + '%)' +
      (g.coverage < GN.PASS ? '\n      χαμένα: ' + g.points.map(function (gp, i) {
        return gp.hits.map(function (h, j) { return h ? null : x.skeleton.points[i].must[j].k; }).filter(Boolean);
      }).reduce(function (a, b) { return a.concat(b); }, []).join(' | ') : ''));
  });

  /* Άσχετα λόγια δεν περνάνε. */
  var junk = GN.gradeUnit(u, 'σήμερα πήγα για ψώνια και μετά έπαιξα μπάλα με τον φίλο μου');
  ok(junk.coverage < 0.15, 'άσχετη ομιλία → σχεδόν μηδέν (' + Math.round(junk.coverage * 100) + '%)');
})();

