var FIXES = [
  ['εφήυρε', 'εφηύρε'],
  ['Ἕν οἶδα', 'Ἓν οἶδα'],
  ['φιλόσοφοι, ενώ\nΖητήματα ηθικής', 'φιλόσοφοι, ενώ ζητήματα ηθικής']
];

function norm(s) {
  var out = String(s);
  for (var i = 0; i < FIXES.length; i++) out = out.split(FIXES[i][0]).join(FIXES[i][1]);
  return out
    .replace(/[‘’ʼ´΄]/g, "'")   /* κανονικοποίηση 1 */
    .replace(/\s+/g, ' ')
    .trim();
}

