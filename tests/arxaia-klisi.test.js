/* tests/arxaia-klisi.test.js — Ο ΦΡΟΥΡΟΣ ΤΩΝ ΚΛΙΣΕΩΝ (σελ. 8-21)
 *
 * ⭐⭐⭐ ΣΤΑΘΕΡΗ ΑΡΧΗ 54 ΣΕ ΝΕΟ ΜΕΡΟΣ — Η ΔΙΑΣΤΑΥΡΩΣΗ ΔΕΝΤΡΟΥ ⇄ ΠΙΝΑΚΑ.
 * Το δέντρο ΙΣΧΥΡΙΖΕΤΑΙ κανόνες αναγνώρισης («ουρανικόληκτο → δοτ. πληθ.
 * -ξι»). Οι πίνακες κρατάνε τους ΑΛΗΘΙΝΟΥΣ τύπους. Αν ο ισχυρισμός του
 * δέντρου δεν ισχύει πάνω στον πίνακα που ο ΙΔΙΟΣ δείχνει, τότε η σελίδα
 * διδάσκει με απόλυτη σιγουριά έναν κανόνα αναγνώρισης που δεν δουλεύει —
 * και είναι ακριβώς ο κανόνας που θα εφαρμόσει στο διαγώνισμα.
 * ⛔ Κανένα λειτουργικό test δεν το βλέπει: και τα δύο είναι έγκυρη JS.
 *
 * §Α ΔΙΠΛΗ ΜΕΤΑΓΡΑΦΗ · §Β ΜΗΧΑΝΙΚΟΙ ΕΛΕΓΧΟΙ · §Γ Η ΔΙΑΣΤΑΥΡΩΣΗ
 */
'use strict';

var path = require('path');
var K = require(path.join(__dirname, '..', 'arxaia-klisi-data.js'));

var pass = 0, fail = 0, notes = [];
function ok(c, m){ if (c) pass++; else { fail++; notes.push('✗ ' + m); } }
function eq(a, b, m){ ok(a === b, m + '  →  «' + a + '» ≠ «' + b + '»'); }

/* ═══ §Α · ΔΙΠΛΗ ΜΕΤΑΓΡΑΦΗ ══════════════════════════════════════════
   Γραμμένοι ΞΑΝΑ από τις φωτογραφίες, χωρίς να κοιτάξω το data file.
   ⛔ ΠΟΤΕ μην τους παραγάγεις από το `PARA` — τότε συμφωνούν με κάθε
   λάθος μου τέλεια. Διαλέχτηκαν οι ΕΠΙΚΙΝΔΥΝΟΙ: αυτοί που αλλάζουν θέμα,
   αυτοί που ο τόνος μετακινείται, και τα μεταπλαστά. */
var SECOND = {
  stratiotis: { sg: ['στρατιώτης','στρατιώτου','στρατιώτῃ','στρατιώτην','στρατιῶτα'],
                pl: ['στρατιῶται','στρατιωτῶν','στρατιώταις','στρατιώτας','στρατιῶται'] },
  thalassa:   { sg: ['θάλασσα','θαλάσσης','θαλάσσῃ','θάλασσαν','θάλασσα'],
                pl: ['θάλασσαι','θαλασσῶν','θαλάσσαις','θαλάσσας','θάλασσαι'] },
  anthropos:  { sg: ['ἄνθρωπος','ἀνθρώπου','ἀνθρώπῳ','ἄνθρωπον','ἄνθρωπε'],
                pl: ['ἄνθρωποι','ἀνθρώπων','ἀνθρώποις','ἀνθρώπους','ἄνθρωποι'] },
  doron:      { sg: ['δῶρον','δώρου','δώρῳ','δῶρον','δῶρον'],
                pl: ['δῶρα','δώρων','δώροις','δῶρα','δῶρα'] },
  polis:      { sg: ['πόλις','πόλεως','πόλει','πόλιν','πόλι'],
                pl: ['πόλεις','πόλεων','πόλεσι','πόλεις','πόλεις'] },
  basileus:   { sg: ['βασιλεύς','βασιλέως','βασιλεῖ','βασιλέα','βασιλεῦ'],
                pl: ['βασιλεῖς','βασιλέων','βασιλεῦσι','βασιλέας','βασιλεῖς'] },
  korax:      { sg: ['κόραξ','κόρακος','κόρακι','κόρακα','κόραξ'],
                pl: ['κόρακες','κοράκων','κόραξι','κόρακας','κόρακες'] },
  patir:      { sg: ['πατήρ','πατρός','πατρί','πατέρα','πάτερ'],
                pl: ['πατέρες','πατέρων','πατράσι','πατέρας','πατέρες'] },
  anir:       { sg: ['ἀνήρ','ἀνδρός','ἀνδρί','ἄνδρα','ἄνερ'],
                pl: ['ἄνδρες','ἀνδρῶν','ἀνδράσι','ἄνδρας','ἄνδρες'] },
  gyni:       { sg: ['γυνή','γυναικός','γυναικί','γυναῖκα','γύναι'],
                pl: ['γυναῖκες','γυναικῶν','γυναιξί','γυναῖκας','γυναῖκες'] },
  naus:       { sg: ['ναῦς','νεώς','νηΐ','ναῦν','ναῦ'],
                pl: ['νῆες','νεῶν','ναυσί','ναῦς','νῆες'] },
  zeus:       { sg: ['Ζεύς','Διός','Διί','Δία','Ζεῦ'], pl: null },
  cheir:      { sg: ['χείρ','χειρός','χειρί','χεῖρα','χείρ'],
                pl: ['χεῖρες','χειρῶν','χερσί','χεῖρας','χεῖρες'] }
};

Object.keys(SECOND).forEach(function (id) {
  var p = K.para(id), s = SECOND[id];
  ok(!!p, 'Α1 · ο πίνακας «' + id + '» υπάρχει');
  if (!p) return;
  ['sg', 'pl'].forEach(function (num) {
    if (s[num] === null){ eq(p[num], null, 'Α2 · «' + id + '» δεν έχει ' + num); return; }
    ok(Array.isArray(p[num]), 'Α2 · «' + id + '» έχει ' + num);
    if (!Array.isArray(p[num])) return;
    eq(p[num].length, 5, 'Α3 · «' + id + '» ' + num + ' έχει 5 πτώσεις');
    s[num].forEach(function (w, i) {
      eq(p[num][i], w, 'Α4 · ⭐ ΔΙΠΛΗ ΜΕΤΑΓΡΑΦΗ «' + id + '» ' + num + ' ' + K.CASES[i]);
    });
  });
});

/* ═══ §Β · ΜΗΧΑΝΙΚΟΙ ΕΛΕΓΧΟΙ ════════════════════════════════════════
   Πιάνουν λάθη ΚΑΙ ΣΤΙΣ ΔΥΟ μεταγραφές — δηλαδή ό,τι δεν πιάνει η §Α. */
var VOWEL = 'αεηιουωΑΕΗΙΟΥΩ';
/* ⚠️⚠️ Ο ΕΛΕΓΧΟΣ ΤΟΥ OXIA ΓΡΑΦΕΤΑΙ ΜΕ ΡΗΤΟΥΣ ΚΩΔΙΚΟΥΣ, ΠΟΤΕ ΜΕ ΧΑΡΑΚΤΗΡΕΣ.
   Η πρώτη γραφή ήταν κλάση χαρακτήρων `[άέή…]` — και ΜΕΤΡΗΘΗΚΕ ότι είναι
   λάθος: το NFC μετατρέπει μόνο του OXIA → TONOS, οπότε το «ά» που πληκτρο-
   λογεί κανείς μέσα στο ΤΕΣΤ είναι U+03AC, δηλαδή ΤΟ ΣΩΣΤΟ, και ο φρουρός
   κατήγγειλε 40 απολύτως σωστούς τύπους («ταμίαι», «θάλασσα», «κώμη»).
   ⭐ Ο κανόνας: ένας φρουρός για κωδικοποίηση δεν επιτρέπεται να εξαρτάται
   από την κωδικοποίηση του ίδιου του αρχείου του (σταθ. 19, νέα μορφή). */
var OXIA_BAD = /[άέήίόύώΆΈΉΐΊΰΎΌΏ]/;

function marks(w){ return w.normalize('NFD').slice(1); }
function hasAccent(w){ return /[́̀͂]/.test(w.normalize('NFD')); }
function hasBreath(w){ return /[̓̔]/.test(w.normalize('NFD')); }

var forms = 0;
K.PARA.forEach(function (p) {
  ok(/^[a-z0-9-]+$/.test(p.id), 'Β0 · το id «' + p.id + '» είναι λατινικό slug');
  ok(['a','b','g'].indexOf(p.k) >= 0, 'Β0 · «' + p.id + '» δηλώνει κλίση');
  ok(['αρσ','θηλ','ουδ'].indexOf(p.g) >= 0, 'Β0 · «' + p.id + '» δηλώνει γένος');
  eq(p.art.length, 5, 'Β0 · «' + p.id + '» έχει 5 άρθρα');

  ['sg','pl'].forEach(function (num) {
    if (!p[num]) return;
    p[num].forEach(function (w, i) {
      forms++;
      var tag = '«' + p.id + '» ' + num + ' ' + K.CASES[i] + ' («' + w + '»)';
      eq(w, w.normalize('NFC'), 'Β1 · NFC στο ' + tag);
      ok(!OXIA_BAD.test(w), 'Β2 · ⛔ κανένα precomposed OXIA στο ' + tag);
      ok(/^[Ͱ-Ͽἀ-῿]+$/.test(w.normalize('NFC')),
        'Β3 · μόνο ελληνικοί χαρακτήρες στο ' + tag);
      ok(hasAccent(w), 'Β4 · ΤΟΝΟΣ στο ' + tag);
      /* ⭐ μηχανικός ανιχνευτής μονοτονικού: λέξη από φωνήεν ΠΡΕΠΕΙ να
         έχει πνεύμα. Το «ανθρωπος» χωρίς ψιλή περνάει κάθε άλλο test. */
      var first = w.normalize('NFC')[0];
      if (VOWEL.indexOf(first) >= 0 || VOWEL.indexOf(first.toLowerCase()) >= 0)
        ok(hasBreath(w), 'Β5 · ⭐ ΠΝΕΥΜΑ σε αρχικό φωνήεν στο ' + tag);
    });
  });

  /* Η γενική ενικού είναι Η ΚΛΕΙΔΑΡΙΑ όλης της σελίδας — δεν επιτρέπεται
     να είναι ίδια με την ονομαστική σε κανένα ουσιαστικό του corpus. */
  if (p.sg) ok(p.sg[1] !== p.sg[0], 'Β6 · «' + p.id + '»: η γενική διαφέρει από την ονομαστική');
  /* Στα ουδέτερα ονομαστική = αιτιατική = κλητική, πάντα. */
  if (p.g === 'ουδ' && p.sg){
    eq(p.sg[3], p.sg[0], 'Β7 · ουδέτερο «' + p.id + '»: αιτ. ενικού = ονομαστική');
    eq(p.sg[4], p.sg[0], 'Β7 · ουδέτερο «' + p.id + '»: κλητ. ενικού = ονομαστική');
    if (p.pl) eq(p.pl[3], p.pl[0], 'Β7 · ουδέτερο «' + p.id + '»: αιτ. πληθ. = ονομαστική');
  }
});

/* Α΄ κλίση, ΚΑΝΟΝΑΣ 1 ΤΟΥ ΦΥΛΛΑΔΙΟΥ: η γενική πληθυντικού τονίζεται
   ΠΑΝΤΑ στη λήγουσα με περισπωμένη. Ο κανόνας ελέγχεται πάνω στα ΔΕΔΟΜΕΝΑ. */
K.ofKlisi('a').forEach(function (p) {
  if (!p.pl) return;
  var g = p.pl[1].normalize('NFD');
  ok(/͂ν$|ν$/.test(g.replace(/[̀-ͯ]/g, '')) && /͂/.test(g.slice(-4)),
    'Β8 · ⭐ ΚΑΝΟΝΑΣ Α΄1 πάνω στα δεδομένα: «' + p.pl[1] + '» έχει περισπωμένη στη λήγουσα');
});

/* ═══ §Γ · Η ΔΙΑΣΤΑΥΡΩΣΗ ΔΕΝΤΡΟΥ ⇄ ΠΙΝΑΚΑ (σταθ. 54) ═══════════════
   Το δέντρο λέει «ουρανικόληκτο → δοτ. πληθ. -ξι». Ο πίνακας ΠΡΕΠΕΙ να
   το επιβεβαιώνει, αλλιώς διδάσκουμε κανόνα αναγνώρισης που δεν δουλεύει. */
var DOTPL = {
  ouran:    { end: 'ξι', label: 'ουρανικόληκτα' },
  cheil:    { end: 'ψι', label: 'χειλικόληκτα' },
  odont:    { end: 'σι', label: 'οδοντικόληκτα' },
  'odont-nt': { end: 'σι', label: 'οδοντικόληκτα με -ντ' }
};
var crossed = 0;
K.PARA.forEach(function (p) {
  var d = DOTPL[p.cat];
  if (!d || !p.pl) return;
  var dot = p.pl[2].normalize('NFD').replace(/[̀-ͯ]/g, '');
  ok(dot.slice(-2) === d.end,
    'Γ1 · ⭐ ΔΙΑΣΤΑΥΡΩΣΗ: το δέντρο λέει ' + d.label + ' → -' + d.end +
    ', και η δοτ. πληθ. του «' + p.id + '» είναι «' + p.pl[2] + '»');
  crossed++;
});
ok(crossed >= 4, 'Γ2 · διασταυρώθηκαν και οι τέσσερις κατηγορίες αφωνολήκτων (' + crossed + ')');

/* ⚠️ Ο ΠΡΩΤΟΣ ΜΟΥ ΕΛΕΓΧΟΣ ΕΔΩ ΗΤΑΝ ΛΑΘΟΣ, ΚΑΙ ΤΟ ΜΑΘΗΜΑ ΑΞΙΖΕΙ:
   μέτραγε ΜΗΚΟΣ («η γενική είναι κοντύτερη»). Το `ἀνήρ → ἀνδρός` όντως
   συγκόπτεται — χάνει το ε του θέματος ἀνερ- — αλλά ΜΕΓΑΛΩΝΕΙ, γιατί
   παίρνει και την κατάληξη -ος. Ο φρουρός κατηγορούσε σωστά δεδομένα.
   ⭐ Το ΑΛΗΘΙΝΟ μηχανικό σημάδι των συγκοπτόμενων είναι Η ΔΟΤΙΚΗ
   ΠΛΗΘΥΝΤΙΚΟΥ ΣΕ -άσι (πατράσι, ἀνδράσι, θυγατράσι) — υπάρχει σε καμία
   άλλη κατηγορία, φαίνεται με το μάτι, και το ρωτάει το διαγώνισμα.
   Ο κανόνας: όταν ένας φρουρός σκάει, ρώτα ΠΡΩΤΑ αν ο κανόνας που
   κωδικοποίησες είναι όντως ο κανόνας (σταθ. 30). */
var sygkop = 0;
K.PARA.forEach(function (p) {
  if (p.cat !== 'sygkop' || !p.pl) return;
  sygkop++;
  var dot = p.pl[2].normalize('NFD').replace(/[̀-ͯ]/g, '');
  ok(dot.slice(-3) === 'ασι',
    'Γ3 · ⭐ συγκοπτόμενο «' + p.id + '»: δοτ. πληθ. σε -άσι («' + p.pl[2] + '»)');
  /* και η γενική ΟΝΤΩΣ χάνει το φωνήεν του θέματος: η αιτιατική το κρατάει
     ή το αντικαθιστά, αλλά ΠΟΤΕ δεν είναι ίδια ρίζα με τη γενική. */
  ok(p.sg[1] !== p.sg[3], 'Γ3β · «' + p.id + '»: γενική και αιτιατική έχουν άλλο θέμα');
});
ok(sygkop >= 2, 'Γ3γ · ελέγχθηκαν ≥2 συγκοπτόμενα (' + sygkop + ')');

/* Τα διπλόθεμα σε -ις βγάζουν γενική σε -εως, ΟΧΙ σε -ος. Είναι το πιο
   συχνό λάθος αναγνώρισης, γιατί μοιάζουν με οδοντικόληκτα σε -ις. */
var pol = K.para('polis');
ok(pol && /εως$/.test(pol.sg[1]), 'Γ4 · ⭐ «πόλις» → γενική σε -εως, όχι σε -ος');
var pat = K.para('patris');
ok(pat && /ος$/.test(pat.sg[1]), 'Γ5 · ⭐ «πατρίς» → γενική σε -ος, όχι σε -εως');
ok(pol.sg[1] !== pat.sg[1], 'Γ6 · και οι δύο σε -ις ΔΕΝ κλίνονται ίδια — αυτή είναι η παγίδα');

/* Κάθε `para` που δείχνει το δέντρο ΠΡΕΠΕΙ να υπάρχει. Ένας δείκτης που
   δεν λύνεται είναι σιωπηλά άδειο ράφι (σταθ. 10). */
var seen = 0;
(function walk(n){
  (n.kids || []).forEach(function (k) {
    if (k.para){ seen++; ok(!!K.para(k.para), 'Γ7 · το δέντρο δείχνει σε υπαρκτό πίνακα («' + k.para + '»)'); }
    ok(!!k.t && !!k.tell, 'Γ8 · κάθε κλαδί έχει όνομα ΚΑΙ σημάδι αναγνώρισης («' + (k.t || '?') + '»)');
    walk(k);
  });
})(K.TREE);
ok(seen >= 12, 'Γ9 · το δέντρο δείχνει σε ≥12 πίνακες (' + seen + ')');

/* ═══ §Δ · ΤΑ ΤΕΣΣΕΡΑ ΕΠΙΠΕΔΑ ΜΕΝΟΥΝ ΧΩΡΙΣΤΑ ══════════════════════ */
K.RULES.forEach(function (r) {
  ok(r.full.length > 25, 'Δ1 · ο κανόνας ' + r.k + r.n + ' κρατάει τη φράση του φυλλαδίου');
  ok(r.say !== r.full, 'Δ2 · και έχει ΔΙΚΗ ΜΟΥ διατύπωση, ξεχωριστή');
});
ok(K.SOS.length === 8, 'Δ3 · οκτώ SOS, όσα έγραψε με το χέρι του (' + K.SOS.length + ')');
K.SOS.forEach(function (s) { ok(s.p >= 8 && s.p <= 21, 'Δ4 · το SOS δείχνει σε σελίδα της ύλης (σελ. ' + s.p + ')'); });
ok(K.GAPS.length >= 3, 'Δ5 · τα κενά της μεταγραφής δηλώνονται ρητά');

console.log('\narxaia-klisi: ' + pass + ' πέρασαν, ' + fail + ' έπεσαν  ·  ' +
  K.PARA.length + ' πίνακες, ' + forms + ' τύποι, ' + K.RULES.length + ' κανόνες');
if (fail){ console.log('\n' + notes.slice(0, 30).join('\n')); process.exit(1); }
console.log('ΟΛΑ ΠΡΑΣΙΝΑ');
