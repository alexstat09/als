/* ── 5 · ΟΙ ΠΙΝΑΚΕΣ ΕΙΝΑΙ ΟΡΘΟΓΩΝΙΟΙ ΚΑΙ ΤΑ ΝΟΥΜΕΡΑ ΤΟΥ ΒΙΒΛΙΟΥ ─────── */
I.UNITS.forEach(function (u) {
  if (!u.table) return;
  var t = u.table;
  ok(!!t.cap && !!t.n, u.id + ' · ο πίνακας έχει τίτλο');
  t.rows.forEach(function (r, n) {
    eq(r.length, t.head.length, u.id + ' · πίνακας γραμμή ' + n + ' έχει σωστό πλήθος στηλών');
  });
  /* Κάθε αριθμός του πίνακα πρέπει να υπάρχει στο βιβλίο.  Αυτό είναι που
     πιάνει ένα δάχτυλο που γλίστρησε σε ψηφίο. */
  t.rows.forEach(function (r) {
    r.forEach(function (cell) {
      var m = String(cell).match(/[\d][\d.]*/g) || [];
      m.forEach(function (num) {
        if (num.length < 3) return;                       // «—» και μονοψήφια
        ok(BOOK_N.indexOf(num) >= 0, u.id + ' · ο αριθμός ' + num + ' του πίνακα ΔΕΝ ΥΠΑΡΧΕΙ ΣΤΟ ΒΙΒΛΙΟ');
      });
    });
  });
});

