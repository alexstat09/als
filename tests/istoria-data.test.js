/* ⚠️ ΟΙ ΔΥΟ ΜΟΝΕΣ ΕΠΙΤΡΕΠΤΕΣ ΑΠΟΚΛΙΣΕΙΣ ΑΠΟ ΤΟ EBOOK.
   Γράφονται εδώ ώστε να ΦΑΙΝΟΝΤΑΙ.  Κάθε άλλη διαφορά είναι αποτυχία. */
var FIXES = [
  ['Αμβρακικού- Παγασητικού', 'Αμβρακικού-Παγασητικού'],   // κενό μετά την παύλα
  ['4.818..000', '4.818.000']                              // διπλή τελεία
];

/* Σύγκριση κειμένου: μόνο κενά και αποστρόφους ισοπεδώνουμε.  Τόνοι, πεζά,
   στίξη και ΑΡΙΘΜΟΙ μένουν άθικτα — αλλιώς ένας λάθος αριθμός θα περνούσε. */
function norm(s) {
  return String(s)
    .normalize('NFC')
    .replace(/[‘’ʼ΄᾽]/g, "'")
    .replace(/\s+/g, ' ')
    .trim();
}
var BOOK_N = (function () {
  var b = BOOK, i;
  for (i = 0; i < FIXES.length; i++) b = b.split(FIXES[i][0]).join(FIXES[i][1]);
  return norm(b);
})();

