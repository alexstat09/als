/* ── 8γ · ⭐⭐ ΚΑΝΕΝΑ ΣΗΜΕΙΟ ΔΕΝ ΑΝΑΒΕΙ ΣΤΟΙΧΕΙΟ ΑΛΛΟΥ ΣΗΜΕΙΟΥ ──────────
   Το χειρότερο ψέμα που μπορεί να πει αυτή η σελίδα δεν είναι «δεν σε άκουσα»,
   είναι «το είπες» για κάτι που δεν είπε.  Και συμβαίνει ΣΙΩΠΗΛΑ, γιατί το
   `hay` σβήνει τα κενά: μια λέξη-κλειδί βρίσκεται μέσα σε άσχετη λέξη άλλης
   παραγράφου.  Στην als-v455 βρέθηκαν πέντε τέτοια ΜΕ ΤΟ ΜΑΤΙ, σε render.
   Εδώ ελέγχεται μηχανικά: απαγγέλλω ΕΝΑ σημείο με τα λόγια του βιβλίου και
   κανένα στοιχείο κανενός ΑΛΛΟΥ σημείου δεν επιτρέπεται να ανάψει.
   ⚠️ Το έπιασε αμέσως: το ['πρωτ','υλ'] του a2 άναβε από τη λέξη
   «πρωτοβουλίες» (→ «προτοβοιλιεσ», που περιέχει «προτ» ΚΑΙ «ιλ»). */
I.UNITS.forEach(function (u) {
  var P = u.skeleton.points;
  P.forEach(function (src, si) {
    var spoken = src.detail + ' ' + src.must.map(function (e) { return e.k; }).join('. ');
    P.forEach(function (tgt, ti) {
      if (ti === si) return;
      tgt.must.forEach(function (el) {
        ok(!I.matched(el, spoken),
          u.id + ' · το σημείο ' + (si + 1) + ' («' + src.label + '») ΑΝΑΒΕΙ ΞΕΝΟ ΣΤΟΙΧΕΙΟ του ' +
          (ti + 1) + ': «' + el.k + '» → ' + JSON.stringify(el.say));
      });
    });
  });
});

