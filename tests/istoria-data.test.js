  (u.vocab || []).forEach(function (v) {
    ok(v.anchor === undefined, u.id + ' · το λεξιλόγιο «' + v.t + '» ΔΕΝ επιτρέπεται να έχει άγκυρα');
    ok(!!v.d, u.id + ' · λεξιλόγιο «' + v.t + '» έχει εξήγηση');
  });
  (u.context || []).forEach(function (c) {
    ok(c.anchor === undefined, u.id + ' · το πλαίσιο «' + c.t + '» ΔΕΝ επιτρέπεται να έχει άγκυρα');
  });
  ok(!!(u.simple && u.simple.length), u.id + ' · έχει «με απλά λόγια»');
