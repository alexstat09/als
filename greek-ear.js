(function (root, factory) {
  var api = factory();
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.GREEKEAR = api;
}(typeof window !== 'undefined' ? window : globalThis, function () {
  'use strict';

  /* Ορθογραφική κανονικοποίηση: πεζά, χωρίς τόνους, τελικό σίγμα → σίγμα.
     Κρατάει τα κενά — χρησιμοποιείται όπου μετράμε ΛΕΞΕΙΣ. */
  function fold(s) {
    return String(s == null ? '' : s)
      .toLowerCase()
      .normalize('NFD').replace(/[̀-ͯ]/g, '')
      .replace(/ς/g, 'σ')
      .replace(/[^Ͱ-ϿA-Za-z0-9]+/g, ' ')
      .trim();
  }

  /* ⭐ ΦΩΝΗΤΙΚΗ κανονικοποίηση: συγκρίνει ΗΧΟΥΣ, όχι γράμματα.
     ⚠️ ΤΑ ΚΕΝΑ ΦΕΥΓΟΥΝ ΕΠΙΤΗΔΕΣ. Η αναγνώριση σπάει τις σπάνιες λέξεις
     («υπέρ βόσκηση», «αγρά ανάπαυση»), δηλαδή ακριβώς τις λέξεις-κλειδιά
     του διαγωνίσματος, γιατί εκεί είναι πιο αδύναμο το γλωσσικό της
     μοντέλο. Χωρίς κενά, μια σπασμένη λέξη ξαναγίνεται λέξη.
     ⭐ Και δίνει εργαλείο: μια πολυλεκτική φράση γραμμένη ΣΑΝ ΜΙΑ
     συμβολοσειρά απαιτεί ΓΕΙΤΝΙΑΣΗ, ενώ δύο ξεχωριστές απαιτούν παρουσία.
     ⚠️ Το πολυτονικό λύνεται από μόνο του: το NFD σπάει το ἀ σε α + ψιλή
     και η ψιλή πέφτει, όπως και η υπογεγραμμένη (U+0345). Άρα «ᾐδέσθην»
     και «ηδεσθην» είναι η ίδια λέξη — που είναι ό,τι ακριβώς γράφει η
     αναγνώριση φωνής για τα Αρχαία. */
  function pho(s) {
    return String(s == null ? '' : s)
      .toLowerCase()
      .normalize('NFD').replace(/[̀-ͯ]/g, '')
      .replace(/ς/g, 'σ')
      /* ⚠️ ΤΑ ΔΙΨΗΦΑ ΠΡΩΤΑ, ΚΑΙ ΜΑΖΙ ΜΕ ΤΟ β/φ ΤΟΥΣ. Το «ευ» προφέρεται
         /ev/ ή /ef/ ανάλογα με το τι ακολουθεί, οπότε η αναγνώριση γράφει
         άλλοτε «αγορεύω», άλλοτε «αγορέβω», άλλοτε «αγορέφω». Μετρημένο:
         χωρίς αυτό, οι τύποι σε -εύω έπεφταν στο 65%. */
      .replace(/α[υβφ]/g, 'αφ').replace(/ε[υβφ]/g, 'εφ').replace(/η[υβφ]/g, 'ιφ')
      .replace(/ει|οι|υι/g, 'ι').replace(/[ηυ]/g, 'ι')
      .replace(/αι/g, 'ε')
      .replace(/ω/g, 'ο')
      .replace(/([βγδζθκλμνξπρστφχψ])\1+/g, '$1')
      .replace(/[^Ͱ-Ͽa-z0-9]+/g, '');
  }

  /* ── ΟΙ ΑΡΙΘΜΟΙ, ΚΑΙ ΣΤΙΣ ΔΥΟ ΓΛΩΣΣΕΣ ──────────────────────────────
     Η αναγνώριση άλλοτε γράφει «1864» και άλλοτε «χίλια οκτακόσια εξήντα
     τέσσερα». ⚠️ ΠΡΟΣΘΕΤΕΙ, ΔΕΝ ΑΝΤΙΚΑΘΙΣΤΑ. */
  var NUMW = {
    'μηδεν':0,'ενα':1,'ενασ':1,'μια':1,'ενοσ':1,'δυο':2,'δυω':2,
    'τρια':3,'τρεισ':3,'τριων':3,'τεσσερα':4,'τεσσερισ':4,'τεσσαρων':4,
    'πεντε':5,'εξι':6,'εφτα':7,'επτα':7,'οχτω':8,'οκτω':8,'εννια':9,'εννεα':9,
    'δεκα':10,'εντεκα':11,'ενδεκα':11,'δωδεκα':12,'δεκατρια':13,'δεκατεσσερα':14,
    'δεκαπεντε':15,'δεκαεξι':16,'δεκαεφτα':17,'δεκαεπτα':17,'δεκαοχτω':18,
    'δεκαοκτω':18,'δεκαεννια':19,'δεκαεννεα':19,
    'εικοσι':20,'τριαντα':30,'σαραντα':40,'πενηντα':50,'εξηντα':60,
    'εβδομηντα':70,'ογδοντα':80,'ενενηντα':90,
    'εκατο':100,'εκατον':100,'διακοσια':200,'διακοσιεσ':200,'τριακοσια':300,
    'τριακοσιεσ':300,'τετρακοσια':400,'πεντακοσια':500,'εξακοσια':600,
    'εφτακοσια':700,'επτακοσια':700,'οχτακοσια':800,'οκτακοσια':800,
    'εννιακοσια':900,'εννεακοσια':900,
    'χιλια':1000,'χιλιεσ':1000,'χιλιων':1000
  };
  /* Τακτικά ΜΕ ΤΙΣ ΠΤΩΣΕΙΣ ΤΟΥΣ: ο αιώνας λέγεται σχεδόν πάντα σε γενική. */
  var ORDW = {
    'πρωτο':1,'πρωτου':1,'δεφτερο':2,'δευτερο':2,'δευτερου':2,'τριτο':3,'τριτου':3,
    'τεταρτο':4,'τεταρτου':4,'πεμπτο':5,'πεμπτου':5,'εκτο':6,'εκτου':6,
    'εβδομο':7,'εβδομου':7,'ογδοο':8,'ογδοου':8,'ενατο':9,'ενατου':9,
    'δεκατο':10,'δεκατου':10,'ενδεκατο':11,'ενδεκατου':11,'δωδεκατο':12,'δωδεκατου':12,
    'εικοστο':20,'εικοστου':20,'εικοστοφ':20
  };
  var ORD_SUF = ['', 'ου', 'ο', 'οσ', 'η', 'ησ', 'α', 'εσ', 'ων', 'ού'];

  function numbersIn(s) {
    var w = fold(s).split(' '), out = [], run = 0, live = false, ord = false, i, t, v;
    function flush() {
      if (live && run) {
        out.push(String(run));
        if (ord) for (var q = 1; q < ORD_SUF.length; q++) out.push(String(run) + ORD_SUF[q]);
      }
      run = 0; live = false; ord = false;
    }
    for (i = 0; i < w.length; i++) {
      t = w[i];
      if (t === 'χιλιαδεσ' && run) { run *= 1000; live = true; continue; }
      v = NUMW.hasOwnProperty(t) ? NUMW[t] : null;
      if (v === null && ORDW.hasOwnProperty(t)) { v = ORDW[t]; ord = true; }
      if (v === null) { flush(); continue; }
      if (live && run >= 10 && v < 10 && run % 10 === 0) run += v;
      else if (live) run += v;
      else run = v;
      live = true;
    }
    flush();
    return out;
  }
  function expand(s) {
    var n = numbersIn(s);
    return n.length ? s + ' ' + n.join(' ') : String(s == null ? '' : s);
  }

  /* ⭐⭐ Η ΘΕΣΗ ΤΟΥ ΤΟΝΟΥ — ο μόνος τρόπος να ξεχωρίσεις δύο τύπους που
     ακούγονται ίδιοι.

     Το φωνητικό αυτί πετάει τους τόνους επίτηδες, και αυτό είναι σωστό για
     την Ιστορία. Στα Αρχαία όμως γεννάει αληθινή σύγκρουση:

         ἀγγέλλω (ΕΝΣ)  και  ἀγγελῶ (ΜΕΛ)   →  και τα δύο «αγελο»

     Δεν είναι εξαίρεση: κάθε υγρόληκτο ρήμα έχει συνηρημένο μέλλοντα, άρα
     το ίδιο θα συμβεί σε στέλλω/στελῶ, μένω/μενῶ, φαίνω/φανῶ. Χωρίς
     απάντηση, λέγοντας ΜΟΝΟ τον ενεστώτα θα του άναβε και ο μέλλοντας.

     ⭐ Η αναγνώριση φωνής γράφει ΤΟΝΙΣΜΕΝΑ νέα ελληνικά, οπότε ο τόνος
     ΥΠΑΡΧΕΙ στο κείμενο — απλώς τον πετούσαμε. Εδώ τον μετράμε: πόσες
     συλλαβές ΜΕΤΑ την τονισμένη (0 = λήγουσα, 1 = παραλήγουσα, 2 =
     προπαραλήγουσα, -1 = δεν βρέθηκε τόνος).
     ⚠️ Το -1 ΔΕΝ είναι λάθος, είναι «δεν ξέρω»: αν η μηχανή δεν έβαλε
     τόνο, δεν επιτρέπεται να κόψουμε σωστή απάντηση γι' αυτό. */
  var ACC = /[́̀͂]/;                      /* οξεία, βαρεία, περισπωμένη */
  var VOW = /[αεηιουω]/;

  function stress(s) {
    var d = String(s == null ? '' : s).toLowerCase().normalize('NFD');
    var i, at = -1, groups = 0, inV = false, ch;
    /* πού πέφτει ο τόνος */
    for (i = 0; i < d.length; i++) if (ACC.test(d[i])) { at = i; break; }
    if (at < 0) return -1;
    /* πόσες φωνηεντικές ομάδες ακολουθούν (η δίφθογγος μετράει μία) */
    for (i = at + 1; i < d.length; i++) {
      ch = d[i];
      if (ACC.test(ch) || /[̀-ͯ]/.test(ch)) continue;   /* σημάδια, όχι γράμματα */
      if (VOW.test(ch)) { if (!inV) { groups++; inV = true; } }
      else inV = false;
    }
    return groups;
  }
  /* Ίδιος ήχος ΚΑΙ συμβατός τόνος. Άγνωστος τόνος = δεκτός. */
  function sameStress(a, b) {
    var x = stress(a), y = stress(b);
    return x < 0 || y < 0 || x === y;
  }

  /* Η «θημωνιά»: ό,τι ακούστηκε, έτοιμο για ψάξιμο. Μία φορά ανά βαθμολόγηση. */
  function hay(heard) { return pho(expand(heard)); }
  /* Υπάρχει η λέξη μέσα σε ό,τι ακούστηκε; */
  function has(h, word) { return h.indexOf(pho(word)) >= 0; }
  /* Όλες οι λέξεις μιας εναλλακτικής; */
  function hasAll(h, words) {
    for (var i = 0; i < words.length; i++) if (!has(h, words[i])) return false;
    return words.length > 0;
  }

  /* Πολύ κοντές φράσεις δεν γίνονται δεκτές ως «το είπα αυτό»: μια σκέτη
     «ναι» θα άναβε οτιδήποτε. */
  var ALIAS_MIN = 6;

  /* ⭐ ΔΙΑΛΕΓΕΙ, ΔΕΝ ΓΡΑΦΕΙ. Επιστρέφει την πρόταση ΤΟΥ που μοιάζει
     περισσότερο με το ζητούμενο. Ένα σύστημα που μπορεί να ΓΡΑΨΕΙ την
     απόδειξη μπορεί και να την εφεύρει. */
  function bestSentence(heard, key) {
    var parts = String(heard == null ? '' : heard).split(/[.!?·;\n]+/);
    var k = pho(key), best = '', score = 0, i, g, n, s, p;
    if (k.length < 4) return '';
    for (i = 0; i < parts.length; i++) {
      p = parts[i].trim(); if (!p) continue;
      s = pho(p); if (s.length < ALIAS_MIN) continue;
      n = 0;
      for (g = 0; g + 4 <= k.length; g++) if (s.indexOf(k.substr(g, 4)) >= 0) n++;
      if (n > score) { score = n; best = p; }
    }
    return score > 0 ? best.trim() : '';
  }

  return {
    fold: fold, pho: pho,
    numbersIn: numbersIn, expand: expand,
    hay: hay, has: has, hasAll: hasAll,
    bestSentence: bestSentence, ALIAS_MIN: ALIAS_MIN,
    stress: stress, sameStress: sameStress
  };
}));
