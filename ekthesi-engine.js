/* ══════════════════════════════════════════════════════════════════════
   ekthesi-engine.js — Ο ΒΑΘΜΟΛΟΓΗΤΗΣ ΤΗΣ ΓΡΑΠΤΗΣ ΑΝΑΚΛΗΣΗΣ

   Η Ιστορία και τα Αρχαία-ΓΝΩΣΤΟ βαθμολογούνται ΑΠΑΓΓΕΛΙΑ (lesson-grade.js):
   μιλάει, και το `pho()` συγχωρεί την ορθογραφία γιατί η ορθογραφία ΔΕΝ
   εξετάζεται εκεί — η αναγνώριση φωνής γράφει, όχι αυτός.

   ⭐⭐ ΕΔΩ ΕΙΝΑΙ ΤΟ ΑΝΤΙΘΕΤΟ, ΚΑΙ ΓΙ' ΑΥΤΟ ΕΙΝΑΙ ΔΙΚΟ ΤΟΥ ΑΡΧΕΙΟ.
   Στην Έκθεση ΓΡΑΦΕΙ ο ίδιος, με το χέρι, στο χαρτί. Ένα «αδωροδόκιτος»
   είναι ΑΝΑΚΛΗΣΗ ΠΕΤΥΧΗΜΕΝΗ και ΟΡΘΟΓΡΑΦΙΑ ΧΑΜΕΝΗ — δύο διαφορετικά
   πράγματα που καμία δυαδική απάντηση δεν μπορεί να πει ταυτόχρονα.

     - Ένας βαθμολογητής που δέχεται μόνο τέλεια ορθογραφία του λέει «δεν
       την ξέρεις τη λέξη», που είναι ψέμα, και τον στέλνει να ξαναμάθει
       κάτι που ήδη ξέρει.
     - Ένας βαθμολογητής με σκέτο `pho()` του λέει «τέλεια», και την Πέμπτη
       χάνει μονάδες σε λέξη που η οθόνη του είχε πει ΣΩΣΤΗ. Αυτό είναι το
       χειρότερο από τα δύο: σιωπηλή ζημιά με καλή φήμη.

   ⭐ Άρα ΤΡΕΙΣ ΒΑΘΜΙΔΕΣ ΠΟΥ ΜΕΤΡΑΝΕ, ΔΥΟ ΠΟΥ ΔΕΝ ΜΕΤΡΑΝΕ:

       ok    ίδια γράμματα (χωρίς τόνους/τελικό σίγμα)  → τέλεια
       spell ίδιος ΗΧΟΣ, άλλα γράμματα                  → μετράει + ΟΡΘΟΓΡΑΦΙΑ
       form  ίδιο θέμα, άλλη κατάληξη                    → μετράει + ΚΑΤΑΛΗΞΗ
       ─────────────────────────────────────────────────────────────────
       cross σωστό, αλλά στο ΛΑΘΟΣ κουτί                 → δεν μετράει, ΔΙΔΑΣΚΕΙ
       extra εκτός λεξικού                               → ΟΥΤΕ μετράει ΟΥΤΕ κόβει
       missed δεν το έγραψε                              → το χρέος

   ⭐ ΤΟ `extra` ΔΕΝ ΤΙΜΩΡΕΙΤΑΙ ΠΟΤΕ, ΚΑΙ ΕΙΝΑΙ ΑΠΟΦΑΣΗ. Το βιβλίο δίνει
   ΤΡΙΑ συνώνυμα του «αδαής»· η γλώσσα δίνει δεκαπέντε. Αν γράψει
   «αστοιχείωτος» δεν έκανε λάθος — έγραψε κάτι που δεν ξέρουμε να
   ελέγξουμε. Σταθερή αρχή 33: ένα «δεν ξέρω» δεν βαφτίζεται «λάθος».
   Και δεν καλείται μοντέλο να κρίνει: ένα μοντέλο που μπορεί να ΕΓΚΡΙΝΕΙ
   συνώνυμο μπορεί και να εγκρίνει λάθος συνώνυμο, με σιγουριά, τη νύχτα
   πριν το διαγώνισμα.

   ⚠️⚠️ ΠΛΗΡΗΣ ΤΑΥΤΙΣΗ, ΠΟΤΕ `indexOf`. Το `pho()` σβήνει ΚΑΙ τα διπλά
   σύμφωνα, οπότε μια υποσυμβολοσειρά ανάβει λέξεις που δεν ειπώθηκαν —
   ακριβώς η παγίδα που κόστισε την als-v493 στην Ιστορία. Εκεί το κείμενο
   είναι μια συνεχής απαγγελία και δεν γίνεται αλλιώς· εδώ η απάντηση
   έρχεται σε ΔΙΑΚΡΙΤΑ κομμάτια χωρισμένα με κόμμα, άρα η ταύτιση είναι
   ΟΛΟΚΛΗΡΗ ΛΕΞΗ ΠΡΟΣ ΟΛΟΚΛΗΡΗ ΛΕΞΗ και δεν υπάρχει δικαιολογία.
   ══════════════════════════════════════════════════════════════════════ */
(function (root, factory) {
  var api = factory(
    (typeof module !== 'undefined' && module.exports && typeof require === 'function')
      ? require('./greek-ear.js') : root.GREEKEAR
  );
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.EkthesiEngine = api;
}(typeof window !== 'undefined' ? window : globalThis, function (EAR) {
  'use strict';

  /* ⚠️ Σταθερή αρχή 10: αυτί που δεν φορτώθηκε δεν επιτρέπεται να μοιάζει με
     αυτί που δεν ακούει. Σκάει δυνατά, δεν βαθμολογεί σιωπηλά με μηδέν. */
  if (!EAR) throw new Error('ekthesi-engine.js: λείπει το greek-ear.js');

  var fold = EAR.fold, pho = EAR.pho;

  /* ── ΤΟ ΚΟΨΙΜΟ ΤΗΣ ΑΠΑΝΤΗΣΗΣ ──────────────────────────────────────
     Γράφει όπως γράφει στο χαρτί: «ανίδεος, άπειρος και άσχετος».
     Κόβουμε σε κόμμα, άνω τελεία, ερωτηματικό-ελληνικό, παύλα, αλλαγή
     γραμμής ΚΑΙ στο σκέτο «και» — που είναι λέξη-σύνδεσμος, ποτέ απάντηση.
     ⚠️ ΤΟ ΚΕΝΟ ΔΕΝ ΕΙΝΑΙ ΔΙΑΧΩΡΙΣΤΗΣ: «φιλεύσπλαχνος» δεν σπάει, αλλά μια
     μελλοντική κάρτα μπορεί να έχει απάντηση ΦΡΑΣΗ («εν ολίγοις»), και ένα
     κενό-διαχωριστής θα την είχε σκοτώσει πριν καν γραφτεί.

     ⚠️⚠️ ΤΟ «και» ΚΟΒΕΤΑΙ ΜΕ ΚΕΝΑ, ΟΧΙ ΜΕ `\b` — ΚΑΙ ΑΥΤΟ ΕΙΝΑΙ ΠΑΓΙΔΑ ΠΟΥ
     ΧΤΥΠΗΣΕ ΗΔΗ. Στη JavaScript το `\w` είναι [A-Za-z0-9_], άρα ΚΑΘΕ ελληνικό
     γράμμα μετράει ως ΜΗ-λέξη και το `\bκαι\b` δεν ταιριάζει ΠΟΤΕ σε
     ελληνικό κείμενο. Δεν σκάει· απλώς δεν κόβει, και το «άπειρος και
     άσχετος» γίνεται ΕΝΑ αδέσποτο — δηλαδή δύο σωστές απαντήσεις
     χαμένες, σιωπηλά. Ο δεύτερος φρουρός είναι το φιλτράρισμα παρακάτω,
     που πιάνει το «και» όπου κι αν στέκεται. */
  var SPLIT = /[,·;\n\r\t\/|]+|\s+-\s+|(?:^|\s)(?:και|κι)(?=\s)/gi;
  var KAI = /^(και|κι)$/;

  function split(typed) {
    var raw = String(typed == null ? '' : typed).split(SPLIT), out = [], i, t;
    for (i = 0; i < raw.length; i++) {
      t = raw[i].replace(/^[\s.\-–—]+|[\s.\-–—]+$/g, '');
      if (t && !KAI.test(fold(t))) out.push(t);
    }
    return out;
  }

  /* ── ΟΙ ΤΡΕΙΣ ΣΥΓΚΡΙΣΕΙΣ ──────────────────────────────────────────── */

  /* 1. Ορθογραφική ταυτότητα. Ο τόνος και το τελικό σίγμα ΔΕΝ είναι λάθος
        ορθογραφίας εδώ: πληκτρολογεί σε κινητό, και το «αδαησ» αντί
        «αδαής» είναι το πληκτρολόγιο, όχι η γνώση του. */
  function same(a, b) { return fold(a) === fold(b); }

  /* 2. Ηχητική ταυτότητα. ΠΛΗΡΗΣ, όχι υποσυμβολοσειρά. */
  function sounds(a, b) { var x = pho(a); return x.length > 0 && x === pho(b); }

  /* 3. ⭐ ΙΔΙΟ ΘΕΜΑ, ΑΛΛΗ ΚΑΤΑΛΗΞΗ — και ΓΙΑΤΙ ΕΙΝΑΙ ΑΣΦΑΛΕΣ.
        Το βιβλίο τυπώνει ονομαστική αρσενικού («ανίδεος»)· γράφοντας
        γρήγορα βγαίνει «ανίδεη» ή «ανιδεότητα». Ίδιο λήμμα, τετριμμένη
        ολίσθηση — αλλά ΔΕΝ γίνεται να δεχτούμε «ό,τι αρχίζει ίδια», γιατί
        στην ΙΔΙΑ σελίδα ζουν «αναίτιος» και «αναιτιολόγητος».

        Ο φρουρός είναι Η ΟΥΡΑ, όχι το ποσοστό: μετά το κοινό πρόθεμα, ΚΑΙ
        ΟΙ ΔΥΟ λέξεις πρέπει να τελειώνουν μέσα σε 2 χαρακτήρες.
            ανετιοσ / ανετιολογιτοσ → κοινά 5, ουρά 8  ✗ ΑΠΟΡΡΙΠΤΕΤΑΙ
            αγαθοσ  / αγαθο         → κοινά 5, ουρά 1  ✓
            δολιοσ  / δολεροσ       → κοινά 3, ουρά 4  ✗ ΑΠΟΡΡΙΠΤΕΤΑΙ
        Το ποσοστό (0.6) και το `p >= 4` απλώς εμποδίζουν κοντές λέξεις να
        ταιριάξουν με τα δύο πρώτα τους γράμματα. */
  function stem(a, b) {
    var x = pho(a), y = pho(b);
    if (!x.length || !y.length) return false;
    if (x === y) return true;
    var L = Math.max(x.length, y.length), S = Math.min(x.length, y.length), p = 0;
    if (L - S > 2) return false;
    while (p < S && x.charAt(p) === y.charAt(p)) p++;
    if (L - p > 2) return false;
    return p >= 4 && (p / L) >= 0.6;
  }

  /* ── ΒΑΘΜΟΛΟΓΗΣΗ ΜΙΑΣ ΟΜΑΔΑΣ ──────────────────────────────────────
     ⭐ ΣΕ ΤΡΙΑ ΠΕΡΑΣΜΑΤΑ, ΚΑΙ Η ΣΕΙΡΑ ΕΙΝΑΙ ΤΟ ΠΑΝ. Αν βαθμολογούσαμε
     λέξη-λέξη, ένα χαλαρό ταίριασμα θα άρπαζε τη θέση ενός τέλειου: το
     «διαρκεια» θα κούμπωνε στο «διαρκής» ως `form` πριν προλάβει το
     σωστό «διαρκής» να κουμπώσει ως `ok`. Πρώτα ΟΛΑ τα τέλεια, μετά ΟΛΑ
     τα ηχητικά, μετά ΟΛΑ τα θεματικά. Ντετερμινιστικό, ανεξάρτητο από τη
     σειρά που τα έγραψε. */
  var TIERS = [
    { st: 'ok',    fn: same },
    { st: 'spell', fn: sounds },
    { st: 'form',  fn: stem }
  ];

  /* ⭐ ΤΟ ΣΤΟΙΧΕΙΟ ΜΠΟΡΕΙ ΝΑ ΕΧΕΙ ΔΕΥΤΕΡΗ ΑΠΟΔΕΚΤΗ ΓΡΑΦΗ (`alt`) — δες το
     `ekthesi-data.js`. Ο βαθμολογητής δέχεται ΟΠΟΙΑΔΗΠΟΤΕ από αυτές· η
     σελίδα δείχνει ΠΑΝΤΑ την πρώτη. Δέχεται και σκέτη συμβολοσειρά, ώστε
     να μπορεί να κληθεί με μια απλή λίστα λέξεων χωρίς τελετουργικό. */
  function asItem(x) {
    if (x && typeof x === 'object' && !Array.isArray(x)) {
      return { w: String(x.w == null ? '' : x.w), alt: x.alt || [] };
    }
    if (Array.isArray(x)) return { w: String(x[0]), alt: x.slice(1) };
    return { w: String(x == null ? '' : x), alt: [] };
  }

  function hit(fn, tok, it) {
    var i;
    if (fn(tok, it.w)) return true;
    for (i = 0; i < it.alt.length; i++) if (fn(tok, it.alt[i])) return true;
    return false;
  }

  function gradeGroup(typed, items) {
    var toks = split(typed), src = items || [], n = src.length,
        its = [], rows = [], used = [], t, i, j, k;

    for (i = 0; i < n; i++) {
      its.push(asItem(src[i]));
      rows.push({ item: its[i].w, status: 'missed', typed: '' });
    }
    for (i = 0; i < toks.length; i++) used.push(false);

    for (t = 0; t < TIERS.length; t++) {
      for (i = 0; i < n; i++) {
        if (rows[i].status !== 'missed') continue;
        for (j = 0; j < toks.length; j++) {
          if (used[j]) continue;
          if (!hit(TIERS[t].fn, toks[j], its[i])) continue;
          rows[i].status = TIERS[t].st;
          rows[i].typed = toks[j];
          used[j] = true;
          break;
        }
      }
    }

    var got = 0, clean = 0, extras = [];
    for (i = 0; i < n; i++) {
      if (rows[i].status !== 'missed') got++;
      if (rows[i].status === 'ok') clean++;
    }
    for (k = 0; k < toks.length; k++) if (!used[k]) extras.push(toks[k]);

    return {
      total: n, got: got, clean: clean,
      rows: rows, extras: extras,
      score: n ? got / n : 0
    };
  }

  /* ── ΒΑΘΜΟΛΟΓΗΣΗ ΟΛΗΣ ΤΗΣ ΚΑΡΤΑΣ ──────────────────────────────────
     ⭐ ΕΔΩ ΓΕΝΝΙΕΤΑΙ ΤΟ `cross`, ΠΟΥ ΕΙΝΑΙ Η ΠΙΟ ΧΡΗΣΙΜΗ ΑΠΑΝΤΗΣΗ ΤΗΣ
     ΣΕΛΙΔΑΣ. Ένα αδέσποτο του κουτιού «συνώνυμα» που βρίσκεται μέσα στα
     ΑΝΤΩΝΥΜΑ της ίδιας κάρτας δεν είναι άγνωστη λέξη: είναι ακριβώς η
     σύγχυση που θα του κοστίσει την Πέμπτη, και μόνο εδώ φαίνεται.
     ⚠️ ΔΕΝ ΜΕΤΡΑΕΙ ΣΑΝ ΣΩΣΤΟ. Δεν είναι τιμωρία — είναι άρνηση να
     βαθμολογηθεί σωστά κάτι που μπήκε σε λάθος στήλη, γιατί στο χαρτί
     ακριβώς αυτό είναι λάθος. */
  function gradeCard(answers, card) {
    var gs = (card && card.groups) || [], out = {}, i, j, g, res,
        total = 0, got = 0, clean = 0, spell = 0, form = 0, cross = 0;

    for (i = 0; i < gs.length; i++) {
      g = gs[i];
      res = gradeGroup((answers && answers[g.id]) || '', g.items || []);
      res.id = g.id; res.label = g.label;
      out[g.id] = res;
    }

    /* δεύτερο βλέμμα: τα αδέσποτα, μέσα στις ΑΛΛΕΣ ομάδες */
    for (i = 0; i < gs.length; i++) {
      res = out[gs[i].id];
      res.cross = [];
      for (j = 0; j < res.extras.length; j++) {
        var w = res.extras[j], found = null, a, b, items;
        for (a = 0; a < gs.length && !found; a++) {
          if (gs[a].id === gs[i].id) continue;
          items = gs[a].items || [];
          for (b = 0; b < items.length; b++) {
            var oi = asItem(items[b]);
            if (hit(same, w, oi) || hit(sounds, w, oi)) { found = { word: w, group: gs[a].id, label: gs[a].label }; break; }
          }
        }
        if (found) res.cross.push(found);
      }
      /* τα αδέσποτα που ΕΞΗΓΗΘΗΚΑΝ φεύγουν από τα «εκτός λεξικού» */
      if (res.cross.length) {
        var keep = [], q, m;
        for (q = 0; q < res.extras.length; q++) {
          for (m = 0; m < res.cross.length; m++) if (res.cross[m].word === res.extras[q]) break;
          if (m === res.cross.length) keep.push(res.extras[q]);
        }
        res.extras = keep;
      }
      total += res.total; got += res.got; clean += res.clean;
      cross += res.cross.length;
      for (j = 0; j < res.rows.length; j++) {
        if (res.rows[j].status === 'spell') spell++;
        if (res.rows[j].status === 'form') form++;
      }
    }

    return {
      groups: out, total: total, got: got, clean: clean,
      spell: spell, form: form, cross: cross,
      score: total ? got / total : 0
    };
  }

  /* ── ΤΟ ΝΗΜΑ ───────────────────────────────────────────────────────
     ⭐⭐ ΓΙΑΤΙ ΥΠΑΡΧΕΙ ΚΑΘΟΛΟΥ. Το να ζητάς «γράψε τα 5 συνώνυμα» είναι
     ΕΛΕΥΘΕΡΗ ΑΝΑΚΛΗΣΗ ΣΥΝΟΛΟΥ — το πιο δύσκολο είδος ανάκλησης που
     υπάρχει. Θυμάται το 1ο και το 2ο και κολλάει στο 4ο, όχι επειδή δεν το
     ξέρει αλλά επειδή δεν υπάρχει τίποτα να το τραβήξει. Το νήμα δίνει το
     ελάχιστο ερέθισμα ώστε η ανάκληση να γίνει ΕΦΙΚΤΗ, και μετά μαζεύεται.

     ⭐ ΔΙΝΕΙ ΚΑΙ ΤΗΝ ΚΑΤΑΛΗΞΗ, ΟΧΙ ΜΟΝΟ ΤΗΝ ΑΡΧΗ. Στα ελληνικά η κατάληξη
     είναι πληροφορία: το «-ος» λέει επίθετο, το «-ία» ουσιαστικό, το «-ω»
     ρήμα. Μια μάσκα που κρύβει το τέλος κρύβει το μισό στοιχείο.

     k = πόσα αρχικά γράμματα φαίνονται. 0 = μόνο το σχήμα. */
  function cue(word, k) {
    var s = String(word == null ? '' : word), n = s.length, head, tail, mid;
    if (!n) return '';
    k = Math.max(0, Math.min(k | 0, n - 1));
    head = s.slice(0, k);
    tail = n > k + 1 ? s.slice(n - 1) : '';
    mid = n - k - tail.length;
    return head + new Array(Math.max(0, mid) + 1).join('·') + tail;
  }

  /* ── Η ΣΚΑΛΑ ───────────────────────────────────────────────────────
     ⚠️ ΕΙΝΑΙ Η ΣΚΑΛΑ ΤΟΥ ΣΠΙΤΙΟΥ [0,3,10,30,90] ΜΕ ΕΝΑ ΣΚΑΛΙ ΜΠΡΟΣΤΑ.
     Το «1» δεν είναι διακόσμηση και δεν είναι διαφωνία με το lesson-grade:
     είναι Η ΠΕΜΠΤΗ. Μαθαίνει Τετάρτη βράδυ για Πέμπτη πρωί, οπότε η πρώτη
     επανάληψη ΕΧΕΙ ήδη ημερομηνία και δεν την ορίζουμε εμείς. Μια σκάλα
     που έλεγε «ξανά σε 3 μέρες» θα του έδινε ραντεβού μετά το διαγώνισμα.

     PASS 0.8, όχι 0.9 όπως στην Ιστορία, και είναι συνειδητό: εκεί η
     μονάδα είναι ΕΝΑ σημείο με 3-4 στοιχεία που λέγονται μαζί σε μια
     πρόταση· εδώ η μονάδα είναι ΕΝΑ λήμμα με ως 9 στοιχεία που γράφονται
     ένα-ένα. Το 0.9 σε λήμμα 5 στοιχείων σημαίνει 5/5 — δηλαδή τιμωρία για
     ένα συνώνυμο σε σελίδα 89 στοιχείων. ⭐ ΚΑΙ ΔΕΝ ΧΑΝΕΤΑΙ ΤΙΠΟΤΑ: το
     στοιχείο που ξέφυγε ζει στον χάρτη ακρίβειας (`els`) και ξαναέρχεται
     ΜΟΝΟ ΤΟΥ, ανεξάρτητα από το αν πέρασε η κάρτα. */
  var LADDER = [0, 1, 3, 10, 30, 90];
  var PASS = 0.8;

  function nextDue(reviews, from) {
    var step = LADDER[Math.min(Math.max(reviews | 0, 0), LADDER.length - 1)];
    return (from || Date.now()) + step * 86400000;
  }

  /* ── Ο ΦΡΟΥΡΟΣ ΤΟΥ ΥΛΙΚΟΥ ─────────────────────────────────────────
     ⭐ ΤΡΕΧΕΙ ΣΤΟ TEST, ΟΧΙ ΣΤΗΝ ΟΘΟΝΗ. Δύο στοιχεία της ΙΔΙΑΣ ομάδας που
     ακούγονται ίδια είναι αδύνατο να ξεχωριστούν από τον βαθμολογητή: θα
     έπαιρνε το ένα και θα χρέωνε το άλλο ως χαμένο, για πάντα, χωρίς
     κανένα σφάλμα πουθενά. Ένα τέτοιο λάθος στο υλικό πρέπει να σκάει τη
     στιγμή που γράφεται η σελίδα του βιβλίου, όχι τη νύχτα πριν το
     διαγώνισμα. Ελέγχει ΚΑΙ το `stem`, γιατί κι αυτό μπερδεύει θέσεις. */
  function collisions(card) {
    var gs = (card && card.groups) || [], out = [], i, a, b, items, x, y, p, q, clash;
    for (i = 0; i < gs.length; i++) {
      items = gs[i].items || [];
      for (a = 0; a < items.length; a++) {
        x = asItem(items[a]);
        for (b = a + 1; b < items.length; b++) {
          y = asItem(items[b]);
          /* ⚠️ ΚΑΘΕ αποδεκτή γραφή του ενός εναντίον ΚΑΘΕ αποδεκτής του
             άλλου. Μια παραλλαγή που συγκρούεται είναι εξίσου θανατηφόρα με
             κανονική γραφή που συγκρούεται — απλώς πιο δύσκολο να τη δεις. */
          clash = false;
          for (p = 0; p <= x.alt.length && !clash; p++) {
            for (q = 0; q <= y.alt.length && !clash; q++) {
              var xs = p ? x.alt[p - 1] : x.w, ys = q ? y.alt[q - 1] : y.w;
              if (sounds(xs, ys) || stem(xs, ys)) clash = true;
            }
          }
          if (clash) out.push({ card: card.id, group: gs[i].id, a: x.w, b: y.w });
        }
      }
    }
    return out;
  }

  return {
    split: split, same: same, sounds: sounds, stem: stem, asItem: asItem,
    gradeGroup: gradeGroup, gradeCard: gradeCard,
    cue: cue, collisions: collisions,
    nextDue: nextDue, LADDER: LADDER, PASS: PASS
  };
}));
