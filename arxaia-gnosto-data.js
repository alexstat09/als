  function alignJoin(un, side) {
    var s = un.align && un.align.segs, out = '', i, j;
    if (!s) return '';
    for (i = 0; i < s.length; i++)
      for (j = 0; j < s[i][side].length; j++) out += s[i][side][j][0];
    return out.replace(/\s+/g, ' ').trim();
  }
